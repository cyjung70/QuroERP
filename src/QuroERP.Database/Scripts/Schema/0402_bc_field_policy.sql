-- bc_field_policy: 필드 정책 회사 재정의 (field-policy.md)
CREATE TABLE bc_field_policy (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    field_key varchar NOT NULL,
    state varchar,
    default_value varchar,
    label_key varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_field_policy PRIMARY KEY (id),
    CONSTRAINT uq_bc_field_policy_field_key UNIQUE (field_key),
    CONSTRAINT ck_bc_field_policy_state CHECK (state IN ('HIDDEN', 'OPTIONAL', 'REQUIRED', 'READONLY'))
);

-- ext_attrs: input-only fields the country pack declares with an ext. key (BC-BR-436)
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['bc_customer', 'bc_vendor', 'bc_item', 'sd_sales_order', 'sd_sales_invoice', 'sd_shipment',
                             'sd_ar_receipt', 'mm_purchase_order', 'mm_goods_receipt', 'mm_ap_payment']
    LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN ext_attrs jsonb NOT NULL DEFAULT ''{}''::jsonb', t);
    END LOOP;
END $$;
