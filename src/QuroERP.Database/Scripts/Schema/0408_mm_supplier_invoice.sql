-- Supplier invoices: the payable that matches goods receipt lines (TASK-MM-047)
-- Definition: database-tables.md (mm_supplier_invoice, mm_supplier_invoice_line), MM supplier-invoice.md
--   MM-BR-751, MM-BR-752, MM-BR-753, MM-BR-755, MM-BR-758, MM-BR-761, MM-BR-764
--   vendor_return_id and vendor_return_line_id are for Debit Memos; their foreign keys come with the vendor return tables.
-- Applied scripts are never edited. Add a new numbered script for changes.

-- mm_supplier_invoice: 공급자 송장. type INV = invoice, DM = Debit Memo (negative, made by a vendor return, MM-BR-762).
-- tot_amt = supply_amt + tax_amt, bal_amt = tot_amt - cls_amt (MM-BR-755); status OP, PA, CL, VO from the amounts (MM-BR-761)
CREATE TABLE mm_supplier_invoice (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    invoice_no varchar NOT NULL,
    type varchar NOT NULL DEFAULT 'INV',
    vendor_id bigint NOT NULL,
    business_place_id bigint NOT NULL,
    ref_no varchar NOT NULL,
    invoice_dt date NOT NULL,
    due_dt date NOT NULL,
    terms varchar,
    currency_code varchar NOT NULL,
    exchange_rate numeric NOT NULL,
    supply_amt numeric NOT NULL DEFAULT 0,
    tax_amt numeric NOT NULL DEFAULT 0,
    tot_amt numeric NOT NULL DEFAULT 0,
    tot_base_amt numeric NOT NULL DEFAULT 0,
    cls_amt numeric NOT NULL DEFAULT 0,
    bal_amt numeric NOT NULL DEFAULT 0,
    status varchar NOT NULL DEFAULT 'OP',
    tax_invoice_received boolean NOT NULL DEFAULT false,
    vendor_return_id bigint,
    remarks varchar,
    ext_attrs jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_supplier_invoice PRIMARY KEY (id),
    CONSTRAINT uq_mm_supplier_invoice_invoice_no UNIQUE (invoice_no),
    CONSTRAINT ck_mm_supplier_invoice_type CHECK (type IN ('INV', 'DM')),
    CONSTRAINT ck_mm_supplier_invoice_status CHECK (status IN ('OP', 'PA', 'CL', 'VO')),
    CONSTRAINT ck_mm_supplier_invoice_exchange_rate CHECK (exchange_rate > 0),
    CONSTRAINT fk_mm_supplier_invoice_vendor_id FOREIGN KEY (vendor_id) REFERENCES bc_vendor (id),
    CONSTRAINT fk_mm_supplier_invoice_business_place_id FOREIGN KEY (business_place_id) REFERENCES bc_business_place (id)
);
CREATE INDEX ix_mm_supplier_invoice_vendor_id ON mm_supplier_invoice (vendor_id);
CREATE INDEX ix_mm_supplier_invoice_business_place_id ON mm_supplier_invoice (business_place_id);
CREATE INDEX ix_mm_supplier_invoice_invoice_dt ON mm_supplier_invoice (invoice_dt);
-- MM-BR-764: one vendor invoice number per vendor among invoices that are not void
CREATE UNIQUE INDEX uq_mm_supplier_invoice_vendor_id_ref_no ON mm_supplier_invoice (vendor_id, ref_no) WHERE status <> 'VO';

-- mm_supplier_invoice_line: 공급자 송장 상세. qty is negative on a Debit Memo; pv_amt is the price variance in base currency
-- posted as a PV movement with ref_key = invoice_no and ref_seq = seq (MM-BR-758)
CREATE TABLE mm_supplier_invoice_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    supplier_invoice_id bigint NOT NULL,
    seq integer NOT NULL,
    goods_receipt_line_id bigint,
    vendor_return_line_id bigint,
    item_id bigint NOT NULL,
    qty numeric NOT NULL,
    prc numeric NOT NULL,
    tax_code_id bigint NOT NULL,
    supply_amt numeric NOT NULL DEFAULT 0,
    tax_amt numeric NOT NULL DEFAULT 0,
    deductible boolean NOT NULL DEFAULT true,
    pv_amt numeric NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_supplier_invoice_line PRIMARY KEY (id),
    CONSTRAINT uq_mm_supplier_invoice_line_supplier_invoice_id_seq UNIQUE (supplier_invoice_id, seq),
    CONSTRAINT fk_mm_supplier_invoice_line_supplier_invoice_id FOREIGN KEY (supplier_invoice_id)
        REFERENCES mm_supplier_invoice (id) ON DELETE CASCADE,
    CONSTRAINT fk_mm_supplier_invoice_line_goods_receipt_line_id FOREIGN KEY (goods_receipt_line_id)
        REFERENCES mm_goods_receipt_line (id),
    CONSTRAINT fk_mm_supplier_invoice_line_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id),
    CONSTRAINT fk_mm_supplier_invoice_line_tax_code_id FOREIGN KEY (tax_code_id) REFERENCES bc_tax_code (id)
);
CREATE INDEX ix_mm_supplier_invoice_line_goods_receipt_line_id ON mm_supplier_invoice_line (goods_receipt_line_id);
CREATE INDEX ix_mm_supplier_invoice_line_item_id ON mm_supplier_invoice_line (item_id);
CREATE INDEX ix_mm_supplier_invoice_line_tax_code_id ON mm_supplier_invoice_line (tax_code_id);
