-- 사용자·역할·메뉴·API 클라이언트 (security.md)
-- 정의: docs/architecture/database-tables.md (database.md, codes.md, i18n.md, inventory.md, security.md)
-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- role: 역할 (security.md, AS IS 코드 S700)
CREATE TABLE role (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    role_code varchar(10) NOT NULL,
    use_yn boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_role PRIMARY KEY (id),
    CONSTRAINT uq_role_role_code UNIQUE (role_code)
);

-- app_user: 사용자 — AS IS `Z_USR_INFO` (User Information)
CREATE TABLE app_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    userid varchar(18),
    password_hash varchar(256),
    password_change_required boolean NOT NULL DEFAULT false,
    username varchar(40),
    role varchar(10),
    email varchar(30),
    phone varchar(18),
    valid_flag varchar(1),
    user_valid_dt timestamp,
    password_valid_dt timestamp,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (id),
    CONSTRAINT uq_app_user_userid UNIQUE (userid)
);

-- user_login_log: 로그인 이력 — AS IS `Z_USR_LOG` (User Login History)
CREATE TABLE user_login_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    log_dt timestamp,
    app_user_id bigint,
    ip_addr varchar(18),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_user_login_log PRIMARY KEY (id),
    CONSTRAINT uq_user_login_log_log_dt UNIQUE (log_dt),
    CONSTRAINT fk_user_login_log_app_user_id FOREIGN KEY (app_user_id) REFERENCES app_user (id)
);
CREATE INDEX ix_user_login_log_app_user_id ON user_login_log (app_user_id);

-- menu: 메뉴 — AS IS `Z_MENU`
CREATE TABLE menu (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    menu_code varchar(10),
    name varchar(30),
    type varchar(1),
    program_id varchar(30),
    module varchar(10),
    parent_menu_id bigint,
    valid_flag varchar(1),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_menu PRIMARY KEY (id),
    CONSTRAINT uq_menu_menu_code UNIQUE (menu_code),
    CONSTRAINT fk_menu_parent_menu_id FOREIGN KEY (parent_menu_id) REFERENCES menu (id)
);
CREATE INDEX ix_menu_parent_menu_id ON menu (parent_menu_id);

-- role_menu: 역할별 메뉴 — AS IS `Z_MENU_TO_ROLE`
CREATE TABLE role_menu (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    role varchar(10),
    menu_id bigint,
    full_access varchar(10),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_role_menu PRIMARY KEY (id),
    CONSTRAINT uq_role_menu_role_menu_id UNIQUE (role, menu_id),
    CONSTRAINT fk_role_menu_menu_id FOREIGN KEY (menu_id) REFERENCES menu (id)
);
CREATE INDEX ix_role_menu_menu_id ON role_menu (menu_id);

-- api_client: 외부 API 클라이언트 (security.md)
CREATE TABLE api_client (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    client_code varchar(50) NOT NULL,
    key_hash varchar(256) NOT NULL,
    role_id bigint NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_api_client PRIMARY KEY (id),
    CONSTRAINT uq_api_client_client_code UNIQUE (client_code),
    CONSTRAINT fk_api_client_role_id FOREIGN KEY (role_id) REFERENCES role (id)
);
CREATE INDEX ix_api_client_role_id ON api_client (role_id);
