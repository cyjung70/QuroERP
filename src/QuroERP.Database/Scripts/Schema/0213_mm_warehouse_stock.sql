VALUES ('MAIN', 'Main', true, 'system', 'system');

-- mm_onhand: 창고별 현재고 (inventory.md, MM ledger.md)
CREATE TABLE mm_onhand (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    item_id bigint NOT NULL,
    warehouse_id bigint NOT NULL,
    onhand_qty numeric NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_onhand PRIMARY KEY (id),
    CONSTRAINT uq_mm_onhand_item_id_warehouse_id UNIQUE (item_id, warehouse_id),
    CONSTRAINT fk_mm_onhand_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id),
    CONSTRAINT fk_mm_onhand_warehouse_id FOREIGN KEY (warehouse_id) REFERENCES bc_warehouse (id)
);
CREATE INDEX ix_mm_onhand_warehouse_id ON mm_onhand (warehouse_id);

INSERT INTO mm_onhand (item_id, warehouse_id, onhand_qty, created_by, updated_by)
SELECT i.id, w.id, i.onhand_qty, 'system', 'system'
FROM bc_item i CROSS JOIN bc_warehouse w
WHERE w.is_default AND coalesce(i.onhand_qty, 0) <> 0;

-- mm_stock_transfer: 창고 이동 (MM warehouse.md)
CREATE TABLE mm_stock_transfer (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    transfer_no varchar NOT NULL,
    transfer_dt date NOT NULL,
    from_warehouse_id bigint NOT NULL,
    to_warehouse_id bigint NOT NULL,
    remarks varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_stock_transfer PRIMARY KEY (id),
    CONSTRAINT uq_mm_stock_transfer_transfer_no UNIQUE (transfer_no),
    CONSTRAINT fk_mm_stock_transfer_from_warehouse_id FOREIGN KEY (from_warehouse_id) REFERENCES bc_warehouse (id),
    CONSTRAINT fk_mm_stock_transfer_to_warehouse_id FOREIGN KEY (to_warehouse_id) REFERENCES bc_warehouse (id)
);
CREATE INDEX ix_mm_stock_transfer_from_warehouse_id ON mm_stock_transfer (from_warehouse_id);
CREATE INDEX ix_mm_stock_transfer_to_warehouse_id ON mm_stock_transfer (to_warehouse_id);

-- mm_stock_transfer_line: 창고 이동 상세 (MM warehouse.md)
CREATE TABLE mm_stock_transfer_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    stock_transfer_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint NOT NULL,
    qty numeric NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_stock_transfer_line PRIMARY KEY (id),
    CONSTRAINT uq_mm_stock_transfer_line_stock_transfer_id_seq UNIQUE (stock_transfer_id, seq),
    CONSTRAINT fk_mm_stock_transfer_line_stock_transfer_id FOREIGN KEY (stock_transfer_id) REFERENCES mm_stock_transfer (id) ON DELETE CASCADE,
    CONSTRAINT fk_mm_stock_transfer_line_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_mm_stock_transfer_line_item_id ON mm_stock_transfer_line (item_id);

