-- bc_business_place: 사업장 (organization.md)
CREATE TABLE bc_business_place (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    business_place_code varchar NOT NULL,
    business_place_name varchar NOT NULL,
    is_default boolean NOT NULL DEFAULT false,
    business_reg_no varchar,
    sub_business_no varchar,
    ceo_name varchar,
    business_type varchar,
    business_item varchar,
    addr1 varchar,
    addr2 varchar,
    city varchar,
    state varchar,
    zip_code varchar,
    tel_no varchar,
    use_yn boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_business_place PRIMARY KEY (id),
    CONSTRAINT uq_bc_business_place_business_place_code UNIQUE (business_place_code)
);
-- At most one default business place (BC-BR-319). The MVP keeps exactly one
CREATE UNIQUE INDEX uq_bc_business_place_single_default ON bc_business_place (is_default) WHERE is_default;

-- The default business place, copied from the company (BC-BR-315, BC-BR-319)
INSERT INTO bc_business_place (business_place_code, business_place_name, is_default, business_reg_no, ceo_name, business_type,
                               business_item, tel_no, created_by, updated_by)
SELECT 'MAIN', coalesce(c.name, 'MAIN'), true, nullif(replace(c.register_no, '-', ''), ''), c.represent, c.business_type,
       c.business_item, c.tel_no, 'system', 'system'
FROM (SELECT 1) one
LEFT JOIN (SELECT * FROM bc_company ORDER BY id LIMIT 1) c ON true;

-- business_place_id on the warehouse and the document headers (BC-BR-321)
DO $$
DECLARE
    t text;
    place bigint := (SELECT id FROM bc_business_place WHERE is_default);
BEGIN
    FOREACH t IN ARRAY ARRAY['bc_warehouse', 'sd_sales_order', 'sd_sales_invoice', 'sd_shipment', 'sd_ar_receipt',
                             'mm_purchase_order', 'mm_goods_receipt', 'mm_ap_payment'] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN business_place_id bigint', t);
        EXECUTE format('UPDATE %I SET business_place_id = %s', t, place);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN business_place_id SET NOT NULL', t);
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (business_place_id) REFERENCES bc_business_place (id)',
                       t, 'fk_' || t || '_business_place_id');
        EXECUTE format('CREATE INDEX %I ON %I (business_place_id)', 'ix_' || t || '_business_place_id', t);
    END LOOP;
END $$;
