-- Login policy (docs/architecture/login.md, BC-UC-001, TASK-BC-001)
--   sys_app_user: lockout, last login and password change columns
--   sys_user_login_log: event type, result code and User-Agent
--   New tables: sys_auth_setting (one row), sys_auto_login_token, sys_password_history
--   sys_app_user.default_warehouse_id needs bc_warehouse (0213), so it is added in 0216
-- Applied scripts are never edited. Add a new numbered script for changes.

ALTER TABLE sys_app_user ADD COLUMN password_changed_at timestamptz;
ALTER TABLE sys_app_user ADD COLUMN failed_count smallint NOT NULL DEFAULT 0;
ALTER TABLE sys_app_user ADD COLUMN locked_until timestamptz;
ALTER TABLE sys_app_user ADD COLUMN last_login_at timestamptz;
ALTER TABLE sys_app_user ADD COLUMN last_login_ip varchar;

-- Existing rows only knew success or failure
ALTER TABLE sys_user_login_log ADD COLUMN event_type varchar;
UPDATE sys_user_login_log SET event_type = CASE WHEN success THEN 'LOGIN_OK' ELSE 'LOGIN_FAIL' END;
ALTER TABLE sys_user_login_log ALTER COLUMN event_type SET NOT NULL;
ALTER TABLE sys_user_login_log ADD CONSTRAINT ck_sys_user_login_log_event_type
    CHECK (event_type IN ('LOGIN_OK', 'LOGIN_FAIL', 'LOCKED', 'AUTO_LOGIN', 'LOGOUT', 'UNLOCK'));
ALTER TABLE sys_user_login_log ADD COLUMN result_code varchar;
ALTER TABLE sys_user_login_log ADD COLUMN user_agent varchar;

-- sys_auth_setting: authentication setting, exactly one row
CREATE TABLE sys_auth_setting (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    max_failed_attempts integer NOT NULL DEFAULT 5,
    lockout_minutes integer NOT NULL DEFAULT 60,
    show_remaining_attempts boolean NOT NULL DEFAULT false,
    auto_login_enabled boolean NOT NULL DEFAULT false,
    auto_login_valid_days integer NOT NULL DEFAULT 14,
    session_idle_minutes integer NOT NULL DEFAULT 30,
    allow_concurrent_login boolean NOT NULL DEFAULT true,
    password_min_length integer NOT NULL DEFAULT 8,
    password_required_categories integer NOT NULL DEFAULT 3,
    password_expire_days integer NOT NULL DEFAULT 0,
    password_history_count integer NOT NULL DEFAULT 3,
    password_reset_mode varchar NOT NULL DEFAULT 'ADMIN_ONLY',
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_auth_setting PRIMARY KEY (id),
    CONSTRAINT ck_sys_auth_setting_password_reset_mode CHECK (password_reset_mode IN ('ADMIN_ONLY', 'EMAIL'))
);

-- Only one row may exist
CREATE UNIQUE INDEX uq_sys_auth_setting_single_row ON sys_auth_setting ((true));

INSERT INTO sys_auth_setting (created_by, updated_by) VALUES ('system', 'system');

-- sys_auto_login_token: "Keep me signed in" tokens. Only the SHA-256 hash is stored
CREATE TABLE sys_auto_login_token (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    app_user_id bigint NOT NULL,
    token_hash varchar NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    user_agent varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_auto_login_token PRIMARY KEY (id),
    CONSTRAINT uq_sys_auto_login_token_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_sys_auto_login_token_app_user_id FOREIGN KEY (app_user_id) REFERENCES sys_app_user (id)
);
CREATE INDEX ix_sys_auto_login_token_app_user_id ON sys_auto_login_token (app_user_id);

-- sys_password_history: previous password hashes, so recent passwords are not reused
CREATE TABLE sys_password_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    app_user_id bigint NOT NULL,
    password_hash varchar NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_password_history PRIMARY KEY (id),
    CONSTRAINT fk_sys_password_history_app_user_id FOREIGN KEY (app_user_id) REFERENCES sys_app_user (id)
);
CREATE INDEX ix_sys_password_history_app_user_id ON sys_password_history (app_user_id);
