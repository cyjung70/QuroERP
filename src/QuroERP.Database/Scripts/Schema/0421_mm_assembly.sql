-- Set assembly and disassembly (TASK-SD-072)
-- Definition: database-tables.md (mm_assembly, mm_assembly_line, mm_lot_link), inventory.md "조립·해체", SD set-item.md
--   (SD-BR-514~516), MM lot.md (MM-BR-368)
--   An assembly issues its components (BI) and receives the Set (BP); a disassembly points to its assembly, issues the Set (DA)
--   and gives the components back (DR). The movements carry the assembly number in ref_key.
--   Every step checks what is already there, so the script gives the same schema when it runs again.
-- Applied scripts are never edited. Add a new numbered script for changes.

-- mm_assembly: AS + yymm + 6 digits (SD-BR-514); a disassembly has its own number and the assembly it takes apart
CREATE TABLE IF NOT EXISTS mm_assembly (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    assembly_no varchar NOT NULL,
    assembly_kind varchar NOT NULL,
    assembly_dt date NOT NULL,
    set_item_id bigint NOT NULL,
    qty numeric NOT NULL,
    warehouse_id bigint NOT NULL,
    location_id bigint NOT NULL,
    set_lot_id bigint,
    source_assembly_id bigint,
    status varchar NOT NULL DEFAULT 'OP',
    remarks varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_assembly PRIMARY KEY (id),
    CONSTRAINT uq_mm_assembly_assembly_no UNIQUE (assembly_no),
    CONSTRAINT ck_mm_assembly_assembly_kind CHECK (assembly_kind IN ('ASSEMBLE', 'DISASSEMBLE')),
    CONSTRAINT ck_mm_assembly_status CHECK (status IN ('OP', 'VO')),
    CONSTRAINT ck_mm_assembly_qty CHECK (qty > 0),
    CONSTRAINT ck_mm_assembly_source CHECK ((assembly_kind = 'DISASSEMBLE') = (source_assembly_id IS NOT NULL)),
    CONSTRAINT fk_mm_assembly_set_item_id FOREIGN KEY (set_item_id) REFERENCES bc_item (id),
    CONSTRAINT fk_mm_assembly_warehouse_id FOREIGN KEY (warehouse_id) REFERENCES bc_warehouse (id),
    CONSTRAINT fk_mm_assembly_location_id FOREIGN KEY (location_id) REFERENCES bc_location (id),
    CONSTRAINT fk_mm_assembly_set_lot_id FOREIGN KEY (set_lot_id) REFERENCES mm_lot (id),
    CONSTRAINT fk_mm_assembly_source_assembly_id FOREIGN KEY (source_assembly_id) REFERENCES mm_assembly (id)
);
CREATE INDEX IF NOT EXISTS ix_mm_assembly_assembly_dt ON mm_assembly (assembly_dt);
CREATE INDEX IF NOT EXISTS ix_mm_assembly_set_item_id ON mm_assembly (set_item_id);
CREATE INDEX IF NOT EXISTS ix_mm_assembly_source_assembly_id ON mm_assembly (source_assembly_id);

-- mm_assembly_line: one component part per (Location, Lot), taken by an assembly or given back by a disassembly (SD-BR-515)
CREATE TABLE IF NOT EXISTS mm_assembly_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    assembly_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint NOT NULL,
    qty numeric NOT NULL,
    warehouse_id bigint NOT NULL,
    location_id bigint NOT NULL,
    lot_id bigint NOT NULL,
    prc numeric NOT NULL,
    amt numeric NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_assembly_line PRIMARY KEY (id),
    CONSTRAINT uq_mm_assembly_line_assembly_id_seq UNIQUE (assembly_id, seq),
    CONSTRAINT ck_mm_assembly_line_qty CHECK (qty > 0),
    CONSTRAINT fk_mm_assembly_line_assembly_id FOREIGN KEY (assembly_id) REFERENCES mm_assembly (id),
    CONSTRAINT fk_mm_assembly_line_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id),
    CONSTRAINT fk_mm_assembly_line_warehouse_id FOREIGN KEY (warehouse_id) REFERENCES bc_warehouse (id),
    CONSTRAINT fk_mm_assembly_line_location_id FOREIGN KEY (location_id) REFERENCES bc_location (id),
    CONSTRAINT fk_mm_assembly_line_lot_id FOREIGN KEY (lot_id) REFERENCES mm_lot (id)
);
CREATE INDEX IF NOT EXISTS ix_mm_assembly_line_item_id ON mm_assembly_line (item_id);
CREATE INDEX IF NOT EXISTS ix_mm_assembly_line_lot_id ON mm_assembly_line (lot_id);

-- mm_lot_link: which component Lots went into a Set Lot, for the Lot trace (MM-BR-368)
CREATE TABLE IF NOT EXISTS mm_lot_link (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    set_lot_id bigint NOT NULL,
    component_lot_id bigint NOT NULL,
    assembly_id bigint NOT NULL,
    qty numeric NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_lot_link PRIMARY KEY (id),
    CONSTRAINT uq_mm_lot_link_assembly_id_component_lot_id UNIQUE (assembly_id, component_lot_id),
    CONSTRAINT fk_mm_lot_link_set_lot_id FOREIGN KEY (set_lot_id) REFERENCES mm_lot (id),
    CONSTRAINT fk_mm_lot_link_component_lot_id FOREIGN KEY (component_lot_id) REFERENCES mm_lot (id),
    CONSTRAINT fk_mm_lot_link_assembly_id FOREIGN KEY (assembly_id) REFERENCES mm_assembly (id)
);
CREATE INDEX IF NOT EXISTS ix_mm_lot_link_set_lot_id ON mm_lot_link (set_lot_id);
CREATE INDEX IF NOT EXISTS ix_mm_lot_link_component_lot_id ON mm_lot_link (component_lot_id);

-- mm_lot.assembly_id: the assembly that made the Set Lot (0418 left the column without its key)
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_mm_lot_assembly_id' AND conrelid = 'mm_lot'::regclass) THEN
        ALTER TABLE mm_lot ADD CONSTRAINT fk_mm_lot_assembly_id FOREIGN KEY (assembly_id) REFERENCES mm_assembly (id);
    END IF;
END $$;
