-- code_major_translation: Major 코드 번역 (codes.md, i18n.md)
CREATE TABLE code_major_translation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    major_id bigint NOT NULL,
    lang_code varchar(10) NOT NULL,
    name varchar(100) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_code_major_translation PRIMARY KEY (id),
    CONSTRAINT uq_code_major_translation_major_id_lang_code UNIQUE (major_id, lang_code),
    CONSTRAINT fk_code_major_translation_major_id FOREIGN KEY (major_id) REFERENCES code_major (id) ON DELETE CASCADE
);

-- code_minor_translation: Minor 코드 번역 (codes.md, i18n.md)
