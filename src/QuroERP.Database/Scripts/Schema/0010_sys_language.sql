-- sys_language: language master (i18n.md, BC localization.md BC-BR-401, TASK-CORE-014)
--   lang_code is a BCP 47 primary language subtag (2~3 lower-case letters). en can never be turned off.
--   The seeded rows live here, not in Seed, because sys_app_user.lang_code and bc_company.default_lang_code
--   reference them in schema scripts that run before Seed.
-- sys_app_user.lang_code: the ko/en CHECK becomes a foreign key to sys_language (BC-BR-403)
-- Applied scripts are never edited. Add a new numbered script for changes.

CREATE TABLE sys_language (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    lang_code varchar NOT NULL,
    sort_order integer NOT NULL,
    use_yn boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_language PRIMARY KEY (id),
    CONSTRAINT uq_sys_language_lang_code UNIQUE (lang_code),
    CONSTRAINT ck_sys_language_lang_code CHECK (lang_code ~ '^[a-z]{2,3}$'),
    CONSTRAINT ck_sys_language_en_in_use CHECK (lang_code <> 'en' OR use_yn)
);

INSERT INTO sys_language (lang_code, sort_order, use_yn, created_by, updated_by) VALUES
    ('en', 1, true, 'system', 'system'),
    ('ko', 2, true, 'system', 'system'),
    ('sw', 3, true, 'system', 'system');

ALTER TABLE sys_app_user DROP CONSTRAINT ck_sys_app_user_lang_code;
ALTER TABLE sys_app_user ADD CONSTRAINT fk_sys_app_user_lang_code
    FOREIGN KEY (lang_code) REFERENCES sys_language (lang_code);
CREATE INDEX ix_sys_app_user_lang_code ON sys_app_user (lang_code);
