-- mm_ap_payment: AP payment — AS IS `A_AP_PAYMENT` (A/P Payment Header)
CREATE TABLE mm_ap_payment (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    cls_ap_no varchar NOT NULL,
    vendor_id bigint,
    pay_method varchar NOT NULL,
    cls_dt date NOT NULL,
    ref_no varchar,
    remarks varchar,
    total_amt numeric NOT NULL DEFAULT 0,
    pay_amt numeric NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_ap_payment PRIMARY KEY (id),
    CONSTRAINT uq_mm_ap_payment_cls_ap_no UNIQUE (cls_ap_no),
    CONSTRAINT fk_mm_ap_payment_vendor_id FOREIGN KEY (vendor_id) REFERENCES bc_vendor (id)
);
CREATE INDEX ix_mm_ap_payment_vendor_id_cls_dt ON mm_ap_payment (vendor_id, cls_dt);

-- mm_ap_clear: AP payment line — AS IS `A_AP_CLS` (A/P Payment Detail)
CREATE TABLE mm_ap_clear (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    ap_payment_id bigint,
    seq integer NOT NULL,
    goods_receipt_id bigint,
    cls_dt date NOT NULL,
    cls_amt numeric NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_ap_clear PRIMARY KEY (id),
    CONSTRAINT uq_mm_ap_clear_ap_payment_id_goods_receipt_id UNIQUE (ap_payment_id, goods_receipt_id),
    CONSTRAINT fk_mm_ap_clear_ap_payment_id FOREIGN KEY (ap_payment_id) REFERENCES mm_ap_payment (id),
    CONSTRAINT fk_mm_ap_clear_goods_receipt_id FOREIGN KEY (goods_receipt_id) REFERENCES mm_goods_receipt (id)
);
CREATE INDEX ix_mm_ap_clear_goods_receipt_id ON mm_ap_clear (goods_receipt_id);
