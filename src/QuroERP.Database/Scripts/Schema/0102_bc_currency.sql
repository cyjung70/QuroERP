-- bc_currency: currency master (localization.md, BC localization.md BC-BR-411, TASK-CORE-014)
--   currency_code is ISO 4217 (3 upper-case letters); decimals is the amount decimals (0~4).
-- bc_currency_translation: currency names per language (i18n.md, BC-BR-404)
--   USD and KRW rows live here, not in Seed, because bc_company.base_currency_code (0103) references them.
-- Applied scripts are never edited. Add a new numbered script for changes.

CREATE TABLE bc_currency (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    currency_code varchar NOT NULL,
    decimals integer NOT NULL,
    use_yn boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_currency PRIMARY KEY (id),
    CONSTRAINT uq_bc_currency_currency_code UNIQUE (currency_code),
    CONSTRAINT ck_bc_currency_currency_code CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_bc_currency_decimals CHECK (decimals BETWEEN 0 AND 4)
);

CREATE TABLE bc_currency_translation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    currency_id bigint NOT NULL,
    lang_code varchar NOT NULL,
    name varchar NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_currency_translation PRIMARY KEY (id),
    CONSTRAINT uq_bc_currency_translation_currency_id_lang_code UNIQUE (currency_id, lang_code),
    CONSTRAINT fk_bc_currency_translation_currency_id FOREIGN KEY (currency_id) REFERENCES bc_currency (id) ON DELETE CASCADE
);

