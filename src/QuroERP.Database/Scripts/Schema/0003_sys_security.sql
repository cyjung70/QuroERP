-- 역할·사용자·로그인 이력·메뉴·API 클라이언트 (security.md)
-- 정의: docs/architecture/database-tables.md (database.md, codes.md, i18n.md, inventory.md, security.md)
-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- sys_role
CREATE TABLE sys_role (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    role_code varchar NOT NULL,
    sort_order integer,
    use_yn boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_role PRIMARY KEY (id),
    CONSTRAINT uq_sys_role_role_code UNIQUE (role_code)
);

-- sys_app_user: 사용자 — AS IS `Z_USR_INFO` (User Information)
CREATE TABLE sys_app_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    userid varchar NOT NULL,
    password_hash varchar NOT NULL,
    must_change_password boolean NOT NULL DEFAULT false,
    username varchar,
    role_id bigint,
    email varchar,
    phone varchar,
    valid_flag varchar,
    user_valid_dt date,
    password_valid_dt date,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_app_user PRIMARY KEY (id),
    CONSTRAINT uq_sys_app_user_userid UNIQUE (userid),
    CONSTRAINT fk_sys_app_user_role_id FOREIGN KEY (role_id) REFERENCES sys_role (id)
);
CREATE INDEX ix_sys_app_user_role_id ON sys_app_user (role_id);

-- sys_user_login_log: 로그인 이력 — AS IS `Z_USR_LOG` (User Login History)
CREATE TABLE sys_user_login_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    log_dt timestamptz NOT NULL,
    app_user_id bigint,
    ip_addr varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_user_login_log PRIMARY KEY (id),
    CONSTRAINT uq_sys_user_login_log_log_dt UNIQUE (log_dt),
    CONSTRAINT fk_sys_user_login_log_app_user_id FOREIGN KEY (app_user_id) REFERENCES sys_app_user (id)
);
CREATE INDEX ix_sys_user_login_log_app_user_id ON sys_user_login_log (app_user_id);

-- sys_menu: 메뉴 — AS IS `Z_MENU`
CREATE TABLE sys_menu (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    menu_code varchar NOT NULL,
    name varchar,
    type varchar,
    program_id varchar,
    module varchar,
    parent_menu_id bigint,
    valid_flag varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_menu PRIMARY KEY (id),
    CONSTRAINT uq_sys_menu_menu_code UNIQUE (menu_code),
    CONSTRAINT fk_sys_menu_parent_menu_id FOREIGN KEY (parent_menu_id) REFERENCES sys_menu (id)
);
CREATE INDEX ix_sys_menu_parent_menu_id ON sys_menu (parent_menu_id);

-- sys_role_menu: 역할별 메뉴 — AS IS `Z_MENU_TO_ROLE`
CREATE TABLE sys_role_menu (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    role_id bigint NOT NULL,
    menu_id bigint,
    full_access varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_role_menu PRIMARY KEY (id),
    CONSTRAINT uq_sys_role_menu_role_id_menu_id UNIQUE (role_id, menu_id),
    CONSTRAINT fk_sys_role_menu_role_id FOREIGN KEY (role_id) REFERENCES sys_role (id),
    CONSTRAINT fk_sys_role_menu_menu_id FOREIGN KEY (menu_id) REFERENCES sys_menu (id)
);
CREATE INDEX ix_sys_role_menu_menu_id ON sys_role_menu (menu_id);

-- sys_api_client: 외부 API 클라이언트 (security.md). 컬럼: 새 테이블 표의 주요 컬럼
CREATE TABLE sys_api_client (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    client_code varchar NOT NULL,
    key_hash varchar NOT NULL,
    role_id bigint NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_api_client PRIMARY KEY (id),
    CONSTRAINT uq_sys_api_client_client_code UNIQUE (client_code),
    CONSTRAINT fk_sys_api_client_role_id FOREIGN KEY (role_id) REFERENCES sys_role (id)
);
CREATE INDEX ix_sys_api_client_role_id ON sys_api_client (role_id);
