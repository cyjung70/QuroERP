-- Purchase simulations are saved again (MM-BR-510~513). 0212 dropped the old tables; this script recreates them
-- as defined in docs/architecture/database-tables.md (TASK-CORE-010, DB-IT-03)
-- Applied scripts are never edited. Add a new numbered script for changes.

-- mm_purchase_simulation: purchase simulation — AS IS `M_PS_HDR`
CREATE TABLE mm_purchase_simulation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    ps_no varchar NOT NULL,
    ps_dt date NOT NULL,
    remarks varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_purchase_simulation PRIMARY KEY (id),
    CONSTRAINT uq_mm_purchase_simulation_ps_no UNIQUE (ps_no)
);

-- mm_purchase_simulation_line: purchase simulation line — AS IS `M_PS_DTL`
CREATE TABLE mm_purchase_simulation_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    purchase_simulation_id bigint,
    seq integer NOT NULL,
    item_id bigint NOT NULL,
    m2_qty numeric,
    m1_qty numeric,
    m0_qty numeric,
    open_so_qty numeric,
    open_po_qty numeric NOT NULL DEFAULT 0,
    rop_qty numeric,
    onhand_qty numeric,
    estimated_po_qty numeric NOT NULL DEFAULT 0,
    order_qty numeric NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_purchase_simulation_line PRIMARY KEY (id),
    CONSTRAINT uq_mm_purchase_simulation_line_purchase_simulation_id_seq UNIQUE (purchase_simulation_id, seq),
    CONSTRAINT fk_mm_purchase_simulation_line_purchase_simulation_id FOREIGN KEY (purchase_simulation_id) REFERENCES mm_purchase_simulation (id),
    CONSTRAINT fk_mm_purchase_simulation_line_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_mm_purchase_simulation_line_item_id ON mm_purchase_simulation_line (item_id);
