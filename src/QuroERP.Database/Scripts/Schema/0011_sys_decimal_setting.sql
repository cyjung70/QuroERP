-- sys_decimal_setting: unit price and quantity decimals and rounding mode per module
--   (localization.md, BC localization.md BC-BR-422, BC-BR-424, TASK-CORE-014)
--   Rows come from the company country defaults (Seed 0504).
-- Applied scripts are never edited. Add a new numbered script for changes.

CREATE TABLE sys_decimal_setting (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    module varchar NOT NULL,
    unit_price_decimals integer NOT NULL,
    qty_decimals integer NOT NULL,
    rounding_mode varchar NOT NULL DEFAULT 'HALF_UP',
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_decimal_setting PRIMARY KEY (id),
    CONSTRAINT uq_sys_decimal_setting_module UNIQUE (module),
    CONSTRAINT ck_sys_decimal_setting_module CHECK (module IN ('MM', 'SD')),
    CONSTRAINT ck_sys_decimal_setting_unit_price_decimals CHECK (unit_price_decimals BETWEEN 0 AND 6),
    CONSTRAINT ck_sys_decimal_setting_qty_decimals CHECK (qty_decimals BETWEEN 0 AND 4),
    CONSTRAINT ck_sys_decimal_setting_rounding_mode CHECK (rounding_mode IN ('HALF_UP', 'DOWN'))
);
