-- Location and lot stock key (TASK-CORE-067)
-- Definition: database-tables.md (bc_location, mm_onhand, mm_lot, mm_goods_movement, stock document lines), inventory.md,
--   MM warehouse.md (MM-BR-712~714), MM lot.md (MM-BR-351~365)
--   Stock is kept per item + warehouse + Location + Lot (mm_onhand, MM-BR-714). The separate lot balance table goes away (MM-BR-354).
--   An item without Location or Lot management uses the system value '*', a real row per warehouse (bc_location) and per item
--   (mm_lot) (MM-BR-713, MM-BR-363). Existing stock and documents move to '*'; the system lots MIGRATED and UNKNOWN merge into '*'.
--   Every step checks what is already there, so the script gives the same schema and data when it runs again.
-- Applied scripts are never edited. Add a new numbered script for changes.

-- bc_location: shelves per warehouse, with one system row '*' each (MM-BR-712)
CREATE TABLE IF NOT EXISTS bc_location (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    warehouse_id bigint NOT NULL,
    location_code varchar NOT NULL,
    location_name varchar,
    is_system boolean NOT NULL DEFAULT false,
    use_yn boolean NOT NULL DEFAULT true,
    remarks varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_location PRIMARY KEY (id),
    CONSTRAINT uq_bc_location_warehouse_id_location_code UNIQUE (warehouse_id, location_code),
    CONSTRAINT ck_bc_location_location_code CHECK (location_code = '*' OR location_code ~ '^[A-Z0-9_-]{1,20}$'),
    CONSTRAINT fk_bc_location_warehouse_id FOREIGN KEY (warehouse_id) REFERENCES bc_warehouse (id)
);

INSERT INTO bc_location (warehouse_id, location_code, is_system, created_by, updated_by)
SELECT w.id, '*', true, 'system', 'system' FROM bc_warehouse w
ON CONFLICT (warehouse_id, location_code) DO NOTHING;

-- bc_item: Location management (MM-BR-713, MM-BR-718) and showing Kit/Set components on sales documents (SD-BR-517)
ALTER TABLE bc_item
    ADD COLUMN IF NOT EXISTS location_managed boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS show_components boolean NOT NULL DEFAULT true;

-- mm_lot: lot attributes (MM-BR-364), its origin (MM-BR-367), and the system lot '*' per item (MM-BR-352, MM-BR-363).
--   assembly_id gets its foreign key with mm_assembly (TASK-SD-072).
ALTER TABLE mm_lot
    ADD COLUMN IF NOT EXISTS supplier_lot_no varchar,
    ADD COLUMN IF NOT EXISTS mfg_dt date,
    ADD COLUMN IF NOT EXISTS expiry_dt date,
    ADD COLUMN IF NOT EXISTS received_dt date,
    ADD COLUMN IF NOT EXISTS goods_receipt_line_id bigint,
    ADD COLUMN IF NOT EXISTS assembly_id bigint;
ALTER TABLE mm_lot DROP CONSTRAINT IF EXISTS ck_mm_lot_lot_no;
ALTER TABLE mm_lot ADD CONSTRAINT ck_mm_lot_lot_no CHECK (lot_no = '*' OR lot_no ~ '^[A-Z0-9_-]{1,30}$');
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_mm_lot_goods_receipt_line_id' AND conrelid = 'mm_lot'::regclass) THEN
        ALTER TABLE mm_lot
            ADD CONSTRAINT fk_mm_lot_goods_receipt_line_id FOREIGN KEY (goods_receipt_line_id) REFERENCES mm_goods_receipt_line (id);
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS ix_mm_lot_goods_receipt_line_id ON mm_lot (goods_receipt_line_id);
CREATE INDEX IF NOT EXISTS ix_mm_lot_assembly_id ON mm_lot (assembly_id);

INSERT INTO mm_lot (item_id, lot_no, created_by, updated_by)
SELECT i.id, '*', 'system', 'system' FROM bc_item i
ON CONFLICT (item_id, lot_no) DO NOTHING;

-- The system lots MIGRATED and UNKNOWN become '*' of the same item (MM-BR-363)
CREATE TEMP TABLE tmp_lot_map ON COMMIT DROP AS
SELECT l.id AS old_lot_id, s.id AS star_lot_id
FROM mm_lot l JOIN mm_lot s ON s.item_id = l.item_id AND s.lot_no = '*'
WHERE l.lot_no IN ('MIGRATED', 'UNKNOWN');

UPDATE mm_goods_movement t SET lot_id = m.star_lot_id FROM tmp_lot_map m WHERE t.lot_id = m.old_lot_id;
UPDATE mm_goods_receipt_line t SET lot_id = m.star_lot_id FROM tmp_lot_map m WHERE t.lot_id = m.old_lot_id;
UPDATE sd_shipment_line t SET lot_id = m.star_lot_id FROM tmp_lot_map m WHERE t.lot_id = m.old_lot_id;
UPDATE sd_sales_invoice_line t SET lot_id = m.star_lot_id FROM tmp_lot_map m WHERE t.lot_id = m.old_lot_id;

-- mm_onhand: (item, warehouse) becomes (item, warehouse, Location, Lot) (MM-BR-714, MM-BR-354).
--   A lot balance moves to (Location '*', its lot); what the warehouse total has beyond its lot balances stays on ('*', '*').
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = current_schema() AND table_name = 'mm_onhand' AND column_name = 'location_id') THEN
        ALTER TABLE mm_onhand ADD COLUMN location_id bigint, ADD COLUMN lot_id bigint;

        CREATE TEMP TABLE tmp_lot_onhand ON COMMIT DROP AS
        SELECT o.item_id, o.warehouse_id, coalesce(m.star_lot_id, o.lot_id) AS lot_id, sum(o.onhand_qty) AS onhand_qty,
               min(o.created_by) AS created_by
        FROM mm_lot_onhand o LEFT JOIN tmp_lot_map m ON m.old_lot_id = o.lot_id
        GROUP BY o.item_id, o.warehouse_id, coalesce(m.star_lot_id, o.lot_id);
        DELETE FROM tmp_lot_onhand t USING mm_lot s WHERE s.id = t.lot_id AND s.lot_no = '*';

        ALTER TABLE mm_onhand DROP CONSTRAINT uq_mm_onhand_item_id_warehouse_id;
        UPDATE mm_onhand o
        SET location_id = (SELECT c.id FROM bc_location c WHERE c.warehouse_id = o.warehouse_id AND c.location_code = '*'),
            lot_id = (SELECT s.id FROM mm_lot s WHERE s.item_id = o.item_id AND s.lot_no = '*'),
            onhand_qty = o.onhand_qty - coalesce((SELECT sum(t.onhand_qty) FROM tmp_lot_onhand t
                                                  WHERE t.item_id = o.item_id AND t.warehouse_id = o.warehouse_id), 0);

        INSERT INTO mm_onhand (item_id, warehouse_id, location_id, lot_id, onhand_qty, created_by, updated_by)
        SELECT t.item_id, t.warehouse_id, c.id, t.lot_id, t.onhand_qty, t.created_by, 'system'
        FROM tmp_lot_onhand t JOIN bc_location c ON c.warehouse_id = t.warehouse_id AND c.location_code = '*'
        WHERE t.onhand_qty <> 0;

        ALTER TABLE mm_onhand
            ALTER COLUMN location_id SET NOT NULL,
            ALTER COLUMN lot_id SET NOT NULL,
            ADD CONSTRAINT uq_mm_onhand_item_id_warehouse_id_location_id_lot_id UNIQUE (item_id, warehouse_id, location_id, lot_id),
            ADD CONSTRAINT fk_mm_onhand_location_id FOREIGN KEY (location_id) REFERENCES bc_location (id),
            ADD CONSTRAINT fk_mm_onhand_lot_id FOREIGN KEY (lot_id) REFERENCES mm_lot (id);
        CREATE INDEX ix_mm_onhand_location_id ON mm_onhand (location_id);
        CREATE INDEX ix_mm_onhand_lot_id ON mm_onhand (lot_id);
    END IF;
END $$;
DROP TABLE IF EXISTS mm_lot_onhand;

-- The merged system lots are no longer referenced
DELETE FROM mm_lot l USING tmp_lot_map m WHERE l.id = m.old_lot_id;

-- An existing lot was received on its first incoming movement, else the day it was made (FIFO order, MM-BR-364, MM-BR-716)
UPDATE mm_lot l
SET received_dt = coalesce((SELECT min(g.document_dt) FROM mm_goods_movement g WHERE g.lot_id = l.id AND g.qty > 0), l.created_at::date)
WHERE l.received_dt IS NULL AND l.lot_no <> '*';

-- Location and Lot on the ledger and the stock document lines; existing rows use '*' (MM-BR-713, MM-BR-363)
ALTER TABLE mm_goods_movement ADD COLUMN IF NOT EXISTS location_id bigint;
ALTER TABLE mm_goods_receipt_line ADD COLUMN IF NOT EXISTS location_id bigint;
ALTER TABLE mm_unplanned_receipt_line ADD COLUMN IF NOT EXISTS location_id bigint, ADD COLUMN IF NOT EXISTS lot_id bigint;
ALTER TABLE mm_stock_count_line ADD COLUMN IF NOT EXISTS location_id bigint, ADD COLUMN IF NOT EXISTS lot_id bigint;
ALTER TABLE sd_shipment_line ADD COLUMN IF NOT EXISTS location_id bigint;
ALTER TABLE sd_sales_invoice_line ADD COLUMN IF NOT EXISTS location_id bigint;

UPDATE mm_goods_movement t SET location_id = c.id FROM bc_location c
WHERE t.location_id IS NULL AND c.warehouse_id = t.warehouse_id AND c.location_code = '*';
UPDATE mm_goods_receipt_line t SET location_id = c.id FROM bc_location c
WHERE t.location_id IS NULL AND c.warehouse_id = t.warehouse_id AND c.location_code = '*';
UPDATE mm_unplanned_receipt_line t SET location_id = c.id FROM bc_location c
WHERE t.location_id IS NULL AND c.warehouse_id = t.warehouse_id AND c.location_code = '*';
UPDATE mm_stock_count_line t SET location_id = c.id FROM mm_stock_count h, bc_location c
WHERE t.location_id IS NULL AND h.id = t.stock_count_id AND c.warehouse_id = h.warehouse_id AND c.location_code = '*';
UPDATE sd_shipment_line t SET location_id = c.id FROM bc_location c
WHERE t.location_id IS NULL AND c.warehouse_id = t.warehouse_id AND c.location_code = '*';
UPDATE sd_sales_invoice_line t SET location_id = c.id FROM bc_location c
WHERE t.location_id IS NULL AND c.warehouse_id = t.warehouse_id AND c.location_code = '*';

UPDATE mm_goods_movement t SET lot_id = s.id FROM mm_lot s WHERE t.lot_id IS NULL AND s.item_id = t.item_id AND s.lot_no = '*';
UPDATE mm_goods_receipt_line t SET lot_id = s.id FROM mm_lot s WHERE t.lot_id IS NULL AND s.item_id = t.item_id AND s.lot_no = '*';
UPDATE mm_unplanned_receipt_line t SET lot_id = s.id FROM mm_lot s WHERE t.lot_id IS NULL AND s.item_id = t.item_id AND s.lot_no = '*';
UPDATE mm_stock_count_line t SET lot_id = s.id FROM mm_lot s WHERE t.lot_id IS NULL AND s.item_id = t.item_id AND s.lot_no = '*';
UPDATE sd_shipment_line t SET lot_id = s.id FROM mm_lot s WHERE t.lot_id IS NULL AND s.item_id = t.item_id AND s.lot_no = '*';
UPDATE sd_sales_invoice_line t SET lot_id = s.id FROM mm_lot s WHERE t.lot_id IS NULL AND s.item_id = t.item_id AND s.lot_no = '*';

-- Location is always there. Lot is NOT NULL where the item is; lines whose item column allows NULL (AS IS definition) need a lot
-- whenever they have an item.
ALTER TABLE mm_goods_movement ALTER COLUMN location_id SET NOT NULL, ALTER COLUMN lot_id SET NOT NULL;
ALTER TABLE sd_shipment_line ALTER COLUMN location_id SET NOT NULL, ALTER COLUMN lot_id SET NOT NULL;
ALTER TABLE mm_goods_receipt_line ALTER COLUMN location_id SET NOT NULL;
ALTER TABLE mm_unplanned_receipt_line ALTER COLUMN location_id SET NOT NULL;
ALTER TABLE mm_stock_count_line ALTER COLUMN location_id SET NOT NULL;
ALTER TABLE sd_sales_invoice_line ALTER COLUMN location_id SET NOT NULL;

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['mm_goods_movement', 'mm_goods_receipt_line', 'mm_unplanned_receipt_line', 'mm_stock_count_line',
                             'sd_shipment_line', 'sd_sales_invoice_line'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_' || t || '_location_id' AND conrelid = t::regclass) THEN
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (location_id) REFERENCES bc_location (id)',
                           t, 'fk_' || t || '_location_id');
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_' || t || '_lot_id' AND conrelid = t::regclass) THEN
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (lot_id) REFERENCES mm_lot (id)', t, 'fk_' || t || '_lot_id');
        END IF;
        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I (location_id)', 'ix_' || t || '_location_id', t);
        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I (lot_id)', 'ix_' || t || '_lot_id', t);
    END LOOP;
    FOREACH t IN ARRAY ARRAY['mm_goods_receipt_line', 'mm_unplanned_receipt_line', 'mm_stock_count_line', 'sd_sales_invoice_line'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_' || t || '_lot_id' AND conrelid = t::regclass) THEN
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I CHECK (item_id IS NULL OR lot_id IS NOT NULL)', t, 'ck_' || t || '_lot_id');
        END IF;
    END LOOP;
END $$;

-- Point-in-time balances per key (MM-BR-356, MM-BR-714); replaces the (item, warehouse, lot, date) index of 0404
DROP INDEX IF EXISTS ix_mm_goods_movement_item_id_warehouse_id_lot_id_document_dt;
CREATE INDEX IF NOT EXISTS ix_mm_goods_movement_item_id_warehouse_id_location_id_lot_id_document_dt
    ON mm_goods_movement (item_id, warehouse_id, location_id, lot_id, document_dt);

-- mm_stock_transfer: movement type TR (between warehouses) or LT (Location move in one warehouse) (MM-BR-715);
--   its lines keep one lot from the sending to the receiving side (MM-BR-357)
ALTER TABLE mm_stock_transfer ADD COLUMN IF NOT EXISTS mov_type varchar NOT NULL DEFAULT 'TR';
ALTER TABLE mm_stock_transfer_line
    ADD COLUMN IF NOT EXISTS lot_id bigint,
    ADD COLUMN IF NOT EXISTS from_location_id bigint,
    ADD COLUMN IF NOT EXISTS to_location_id bigint;
UPDATE mm_stock_transfer_line t SET lot_id = s.id FROM mm_lot s WHERE t.lot_id IS NULL AND s.item_id = t.item_id AND s.lot_no = '*';
UPDATE mm_stock_transfer_line t SET from_location_id = c.id FROM mm_stock_transfer h, bc_location c
WHERE t.from_location_id IS NULL AND h.id = t.stock_transfer_id AND c.warehouse_id = h.from_warehouse_id AND c.location_code = '*';
UPDATE mm_stock_transfer_line t SET to_location_id = c.id FROM mm_stock_transfer h, bc_location c
WHERE t.to_location_id IS NULL AND h.id = t.stock_transfer_id AND c.warehouse_id = h.to_warehouse_id AND c.location_code = '*';
ALTER TABLE mm_stock_transfer_line
    ALTER COLUMN lot_id SET NOT NULL,
    ALTER COLUMN from_location_id SET NOT NULL,
    ALTER COLUMN to_location_id SET NOT NULL;
DO $$
DECLARE
    c text;
BEGIN
    FOREACH c IN ARRAY ARRAY['lot_id', 'from_location_id', 'to_location_id'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint
                       WHERE conname = 'fk_mm_stock_transfer_line_' || c AND conrelid = 'mm_stock_transfer_line'::regclass) THEN
            EXECUTE format('ALTER TABLE mm_stock_transfer_line ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES %I (id)',
                           'fk_mm_stock_transfer_line_' || c, c, CASE WHEN c = 'lot_id' THEN 'mm_lot' ELSE 'bc_location' END);
        END IF;
        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON mm_stock_transfer_line (%I)', 'ix_mm_stock_transfer_line_' || c, c);
    END LOOP;
END $$;
