-- sd_bom: set item composition — AS IS `P_BOM` (BOM Master)
CREATE TABLE sd_bom (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    parent_item_id bigint,
    seq integer NOT NULL,
    child_item_id bigint,
    child_qty numeric NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_bom PRIMARY KEY (id),
    CONSTRAINT uq_sd_bom_parent_item_id_seq UNIQUE (parent_item_id, seq),
    CONSTRAINT fk_sd_bom_parent_item_id FOREIGN KEY (parent_item_id) REFERENCES bc_item (id),
    CONSTRAINT fk_sd_bom_child_item_id FOREIGN KEY (child_item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_sd_bom_child_item_id ON sd_bom (child_item_id);

-- sd_mrp_run: MRP run — AS IS `P_MRP` (MRP Product)
CREATE TABLE sd_mrp_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    mrp_no varchar NOT NULL,
    create_dt timestamptz,
    execute_dt timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_mrp_run PRIMARY KEY (id),
    CONSTRAINT uq_sd_mrp_run_mrp_no UNIQUE (mrp_no)
);

-- sd_mrp_part: MRP part — AS IS `P_MRP_PART` (MRP Part(Result))
CREATE TABLE sd_mrp_part (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    mrp_run_id bigint,
    seq integer NOT NULL,
    item_id bigint,
    item_qty numeric,
    item_unit varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_mrp_part PRIMARY KEY (id),
    CONSTRAINT uq_sd_mrp_part_mrp_run_id_seq UNIQUE (mrp_run_id, seq),
    CONSTRAINT fk_sd_mrp_part_mrp_run_id FOREIGN KEY (mrp_run_id) REFERENCES sd_mrp_run (id),
    CONSTRAINT fk_sd_mrp_part_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_sd_mrp_part_item_id ON sd_mrp_part (item_id);

-- sd_mrp_product: MRP product — AS IS `P_MRP_PRODUCT` (MRP Product)
CREATE TABLE sd_mrp_product (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    mrp_run_id bigint,
    seq integer NOT NULL,
    item_id bigint,
    item_qty numeric,
    item_unit varchar,
    sales_order_line_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_mrp_product PRIMARY KEY (id),
    CONSTRAINT uq_sd_mrp_product_mrp_run_id_seq UNIQUE (mrp_run_id, seq),
    CONSTRAINT fk_sd_mrp_product_mrp_run_id FOREIGN KEY (mrp_run_id) REFERENCES sd_mrp_run (id),
    CONSTRAINT fk_sd_mrp_product_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id),
    CONSTRAINT fk_sd_mrp_product_sales_order_line_id FOREIGN KEY (sales_order_line_id) REFERENCES sd_sales_order_line (id)
);
CREATE INDEX ix_sd_mrp_product_item_id ON sd_mrp_product (item_id);
CREATE INDEX ix_sd_mrp_product_sales_order_line_id ON sd_mrp_product (sales_order_line_id);

-- sd_production_result: production result — AS IS `P_PROD_RESULTS_HDR` (Build Product Header)
CREATE TABLE sd_production_result (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    prod_no varchar NOT NULL,
    prod_dt date,
    sales_order_id bigint,
    remarks varchar,
    shop_order varchar,
    requestor varchar,
    dept varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_production_result PRIMARY KEY (id),
    CONSTRAINT uq_sd_production_result_prod_no UNIQUE (prod_no),
    CONSTRAINT fk_sd_production_result_sales_order_id FOREIGN KEY (sales_order_id) REFERENCES sd_sales_order (id)
);
CREATE INDEX ix_sd_production_result_sales_order_id ON sd_production_result (sales_order_id);

-- sd_production_result_line: production result line — AS IS `P_PROD_RESULTS_DTL` (Build Product Detail)
CREATE TABLE sd_production_result_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    production_result_id bigint,
    seq integer NOT NULL,
    item_id bigint,
    prod_qty numeric,
    prod_unit varchar,
    prod_prc numeric,
    prod_amt numeric,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_production_result_line PRIMARY KEY (id),
    CONSTRAINT uq_sd_production_result_line_production_result_id_seq UNIQUE (production_result_id, seq),
    CONSTRAINT fk_sd_production_result_line_production_result_id FOREIGN KEY (production_result_id) REFERENCES sd_production_result (id),
    CONSTRAINT fk_sd_production_result_line_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_sd_production_result_line_item_id ON sd_production_result_line (item_id);
