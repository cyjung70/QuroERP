-- mm_goods_movement: 재고 이동 — AS IS `I_GOODS_MOVEMENT` (Goods Movement)
CREATE TABLE mm_goods_movement (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    document_no varchar NOT NULL,
    document_dt date,
    mov_type varchar,
    dc_flag varchar,
    item_id bigint,
    qty numeric,
    prc numeric,
    amount numeric,
    ref_key varchar,
    ref_seq integer,
    negative_stock boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_goods_movement PRIMARY KEY (id),
    CONSTRAINT uq_mm_goods_movement_document_no UNIQUE (document_no),
    CONSTRAINT fk_mm_goods_movement_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_mm_goods_movement_item_id ON mm_goods_movement (item_id);

