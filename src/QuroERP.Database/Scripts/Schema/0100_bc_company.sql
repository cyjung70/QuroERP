-- bc_company: 회사 — AS IS `B_COMPANY` (Company)
CREATE TABLE bc_company (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar NOT NULL,
    billto varchar,
    shipto varchar,
    contact varchar,
    tel_no varchar,
    fax_no varchar,
    register_no varchar,
    represent varchar,
    email varchar,
    close_year_month varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_company PRIMARY KEY (id),
    CONSTRAINT uq_bc_company_name UNIQUE (name)
);

-- bc_exchange_rate: 환율 — AS IS `B_CURRENCY` (Currency Code)
CREATE TABLE bc_exchange_rate (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    cur_dt date NOT NULL,
    cur_rp numeric,
    cur_won numeric,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_exchange_rate PRIMARY KEY (id),
    CONSTRAINT uq_bc_exchange_rate_cur_dt UNIQUE (cur_dt)
);
