-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- goods_movement: 재고 이동 — AS IS `I_GOODS_MOVEMENT` (Goods Movement)
CREATE TABLE goods_movement (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    document_no varchar(18),
    document_dt timestamp,
    mov_type varchar(3),
    dc_flag varchar(1),
    item_id bigint,
    qty numeric(15,4),
    prc numeric(15,4),
    amount numeric(15,4),
    ref_key varchar(18),
    ref_seq integer,
    negative_stock boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_goods_movement PRIMARY KEY (id),
    CONSTRAINT uq_goods_movement_document_no UNIQUE (document_no),
    CONSTRAINT fk_goods_movement_item_id FOREIGN KEY (item_id) REFERENCES item (id)
);
CREATE INDEX ix_goods_movement_item_id ON goods_movement (item_id);

-- goods_issue: 출고(불출) — AS IS `M_GI_HDR` (Goods Issue Header)
