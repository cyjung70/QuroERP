-- Tax codes, US tax areas and customer tax exemption certificates (tax.md, BC tax.md BC-BR-501~525).
-- DDL only, as listed in docs/architecture/database-tables.md (TASK-CORE-015, DB-IT-03).
-- Rates are percentages (10 = 10%). Country default tax codes (BC-BR-505) are inserted at install,
-- not here. Cross-field rules (BC-BR-503 area required, BC-BR-504 price included) belong to Domain.
-- Applied scripts are never edited. Add a new numbered script for changes.

-- bc_tax_area: US tax area (state + county/city/district combined rate) (BC-BR-511)
CREATE TABLE bc_tax_area (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tax_area_code varchar NOT NULL,
    tax_area_name varchar NOT NULL,
    state_code varchar NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_tax_area PRIMARY KEY (id),
    CONSTRAINT uq_bc_tax_area_tax_area_code UNIQUE (tax_area_code)
);

-- bc_tax_area_rate: tax area rate per effective date (BC-BR-512, BC-BR-513)
CREATE TABLE bc_tax_area_rate (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tax_area_id bigint NOT NULL,
    effective_from date NOT NULL,
    rate numeric NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_tax_area_rate PRIMARY KEY (id),
    CONSTRAINT uq_bc_tax_area_rate_tax_area_id_effective_from UNIQUE (tax_area_id, effective_from),
    CONSTRAINT ck_bc_tax_area_rate_rate CHECK (rate >= 0 AND rate < 100),
    CONSTRAINT fk_bc_tax_area_rate_tax_area_id FOREIGN KEY (tax_area_id) REFERENCES bc_tax_area (id)
);

-- bc_tax_code: tax code (BC-BR-501~506)
CREATE TABLE bc_tax_code (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tax_code varchar NOT NULL,
    tax_kind varchar NOT NULL,
    rate numeric NOT NULL DEFAULT 0,
    tax_area_id bigint,
    price_included boolean NOT NULL DEFAULT false,
    use_yn boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_tax_code PRIMARY KEY (id),
    CONSTRAINT uq_bc_tax_code_tax_code UNIQUE (tax_code),
    CONSTRAINT ck_bc_tax_code_tax_kind CHECK (tax_kind IN
        ('SALES_TAX', 'SALES_TAX_EXEMPT', 'VAT_STANDARD', 'VAT_ZERO', 'VAT_EXEMPT', 'NONE')),
    CONSTRAINT ck_bc_tax_code_rate CHECK (rate >= 0 AND rate < 100),
    CONSTRAINT fk_bc_tax_code_tax_area_id FOREIGN KEY (tax_area_id) REFERENCES bc_tax_area (id)
);
CREATE INDEX ix_bc_tax_code_tax_area_id ON bc_tax_code (tax_area_id);

-- bc_tax_code_translation: tax code name per language (BC-BR-501, i18n.md)
CREATE TABLE bc_tax_code_translation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tax_code_id bigint NOT NULL,
    lang_code varchar NOT NULL,
    name varchar NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_tax_code_translation PRIMARY KEY (id),
    CONSTRAINT uq_bc_tax_code_translation_tax_code_id_lang_code UNIQUE (tax_code_id, lang_code),
    CONSTRAINT fk_bc_tax_code_translation_tax_code_id FOREIGN KEY (tax_code_id) REFERENCES bc_tax_code (id) ON DELETE CASCADE
);

-- sd_customer_tax_exemption: US customer exemption certificate (BC-BR-524, BC-BR-525)
--   valid_to NULL = no expiry. One valid certificate per customer and state is checked in Domain.
CREATE TABLE sd_customer_tax_exemption (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    customer_id bigint NOT NULL,
    certificate_no varchar NOT NULL,
    state_code varchar NOT NULL,
    valid_to date,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_customer_tax_exemption PRIMARY KEY (id),
    CONSTRAINT fk_sd_customer_tax_exemption_customer_id FOREIGN KEY (customer_id) REFERENCES bc_customer (id)
);
CREATE INDEX ix_sd_customer_tax_exemption_customer_id_state_code ON sd_customer_tax_exemption (customer_id, state_code);
