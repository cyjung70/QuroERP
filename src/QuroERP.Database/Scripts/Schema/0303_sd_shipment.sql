-- Shipment and billing split (SD shipment.md, BC-BR-316)
--   sd_shipment(_line): the stock issue document. sd_sales_invoice bills shipment lines and no longer moves stock.
--   bc_company.billing_mode: WITH_SHIPMENT (default, saving a shipment creates its invoice) or SEPARATE.
--   sd_sales_order_line.ship_qty: shipped quantity; the remaining quantity and order status use it (SD-BR-012).
--   sd_sales_invoice_line.shipment_line_id: the shipment line an invoice line bills.
-- Existing invoices (type IV) become a shipment + invoice pair, as if made in WITH_SHIPMENT mode:
--   the shipment and its lines take the invoice and invoice line ids, ship_no = 'SH' + the invoice number digits,
--   every line is fully billed, and the existing stock movements stay as they are.

ALTER TABLE bc_company ADD COLUMN billing_mode varchar NOT NULL DEFAULT 'WITH_SHIPMENT',
    ADD CONSTRAINT ck_bc_company_billing_mode CHECK (billing_mode IN ('WITH_SHIPMENT', 'SEPARATE'));

CREATE TABLE sd_shipment (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    ship_no varchar NOT NULL,
    customer_id bigint NOT NULL,
    sales_order_id bigint,
    ship_dt date NOT NULL,
    warehouse_id bigint NOT NULL,
    currency_code varchar NOT NULL,
    exchange_rate numeric NOT NULL,
    status varchar NOT NULL DEFAULT 'OP',
    ship_via varchar,
    ship_name varchar,
    ship_addr1 varchar,
    ship_addr2 varchar,
    ship_city varchar,
    ship_state varchar,
    ship_country varchar,
    ship_zip_code varchar,
    ship_phone varchar,
    remarks varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_shipment PRIMARY KEY (id),
    CONSTRAINT uq_sd_shipment_ship_no UNIQUE (ship_no),
    CONSTRAINT ck_sd_shipment_status CHECK (status IN ('OP', 'PB', 'BL', 'VO')),
    CONSTRAINT fk_sd_shipment_customer_id FOREIGN KEY (customer_id) REFERENCES bc_customer (id),
    CONSTRAINT fk_sd_shipment_sales_order_id FOREIGN KEY (sales_order_id) REFERENCES sd_sales_order (id),
    CONSTRAINT fk_sd_shipment_warehouse_id FOREIGN KEY (warehouse_id) REFERENCES bc_warehouse (id)
);
CREATE INDEX ix_sd_shipment_customer_id ON sd_shipment (customer_id);
CREATE INDEX ix_sd_shipment_sales_order_id ON sd_shipment (sales_order_id);
CREATE INDEX ix_sd_shipment_warehouse_id ON sd_shipment (warehouse_id);

CREATE TABLE sd_shipment_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    shipment_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint NOT NULL,
    item_name varchar,
    warehouse_id bigint NOT NULL,
    ship_qty numeric NOT NULL,
    ship_prc numeric NOT NULL,
    dc_cd varchar,
    dc_rate numeric,
    billed_qty numeric NOT NULL DEFAULT 0,
    sales_order_line_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_shipment_line PRIMARY KEY (id),
    CONSTRAINT uq_sd_shipment_line_shipment_id_seq UNIQUE (shipment_id, seq),
    CONSTRAINT fk_sd_shipment_line_shipment_id FOREIGN KEY (shipment_id) REFERENCES sd_shipment (id) ON DELETE CASCADE,
    CONSTRAINT fk_sd_shipment_line_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id),
    CONSTRAINT fk_sd_shipment_line_warehouse_id FOREIGN KEY (warehouse_id) REFERENCES bc_warehouse (id),
    CONSTRAINT fk_sd_shipment_line_sales_order_line_id FOREIGN KEY (sales_order_line_id) REFERENCES sd_sales_order_line (id)
);
CREATE INDEX ix_sd_shipment_line_item_id ON sd_shipment_line (item_id);
CREATE INDEX ix_sd_shipment_line_warehouse_id ON sd_shipment_line (warehouse_id);
CREATE INDEX ix_sd_shipment_line_sales_order_line_id ON sd_shipment_line (sales_order_line_id);

ALTER TABLE sd_sales_order_line ADD COLUMN ship_qty numeric NOT NULL DEFAULT 0;
UPDATE sd_sales_order_line SET ship_qty = coalesce(dn_qty, 0);

ALTER TABLE sd_sales_invoice_line ADD COLUMN shipment_line_id bigint,
    ADD CONSTRAINT fk_sd_sales_invoice_line_shipment_line_id FOREIGN KEY (shipment_line_id) REFERENCES sd_shipment_line (id);
CREATE INDEX ix_sd_sales_invoice_line_shipment_line_id ON sd_sales_invoice_line (shipment_line_id);

-- Existing invoices → shipments. Invoices without a customer and lines without an item have no shipment.
INSERT INTO sd_shipment (id, ship_no, customer_id, sales_order_id, ship_dt, warehouse_id, currency_code, exchange_rate, status,
                         ship_via, ship_name, ship_addr1, ship_addr2, ship_city, ship_state, ship_country, ship_zip_code, ship_phone,
                         remarks, created_at, created_by, updated_at, updated_by)
SELECT i.id, 'SH' || substr(i.dn_no, 3), i.customer_id, i.sales_order_id, coalesce(i.ship_dt, i.dn_dt, i.created_at::date), i.warehouse_id,
       coalesce((SELECT base_currency_code FROM bc_company ORDER BY id LIMIT 1), 'USD'), 1,
       CASE WHEN i.status = 'VO' THEN 'VO' ELSE 'BL' END,
       i.ship_via, i.ship_name, i.ship_addr1, i.ship_addr2, i.ship_city, i.ship_state, i.ship_country, i.ship_zip_code, i.ship_phone,
       i.remarks, i.created_at, i.created_by, i.updated_at, i.updated_by
FROM sd_sales_invoice i
WHERE i.type = 'IV' AND i.customer_id IS NOT NULL;

INSERT INTO sd_shipment_line (id, shipment_id, seq, item_id, item_name, warehouse_id, ship_qty, ship_prc, dc_cd, dc_rate, billed_qty,
                              sales_order_line_id, created_at, created_by, updated_at, updated_by)
SELECT l.id, l.sales_invoice_id, l.seq, l.item_id, l.item_name, l.warehouse_id, coalesce(l.dn_qty, 0), coalesce(l.dn_prc, 0), l.dc_cd, l.dc_rate,
       coalesce(l.dn_qty, 0), l.sales_order_line_id, l.created_at, l.created_by, l.updated_at, l.updated_by
FROM sd_sales_invoice_line l
JOIN sd_shipment s ON s.id = l.sales_invoice_id
WHERE l.item_id IS NOT NULL;

UPDATE sd_sales_invoice_line l SET shipment_line_id = l.id
WHERE EXISTS (SELECT 1 FROM sd_shipment_line sl WHERE sl.id = l.id);

-- The copied ids must not be generated again
SELECT setval(pg_get_serial_sequence('sd_shipment', 'id'), coalesce((SELECT max(id) FROM sd_shipment), 0) + 1, false);
SELECT setval(pg_get_serial_sequence('sd_shipment_line', 'id'), coalesce((SELECT max(id) FROM sd_shipment_line), 0) + 1, false);
