-- Warehouse stock and the inventory ledger (ADR-0027, inventory.md, MM ledger.md, MM warehouse.md)
--   New:     bc_warehouse with one default warehouse (MM-BR-702), mm_onhand (item + warehouse), mm_stock_transfer(_line)
--   Ledger:  mm_goods_movement gets warehouse_id and parent_movement_id, loses dc_flag (sign is in qty, MM-BR-606),
--            and its required columns become NOT NULL. mm_monthly_inventory is keyed by item + warehouse
--   Documents: warehouse_id on stock count, goods receipt and unplanned receipt headers and lines
--              (sales invoice: 0301_sd_sales_invoice_warehouse.sql, which runs after 0300)
--   Existing rows go to the default warehouse. mm_onhand starts from bc_item.onhand_qty
-- Applied scripts are never edited. Add a new numbered script for changes.

-- bc_warehouse: 창고 (MM warehouse.md)
CREATE TABLE bc_warehouse (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    warehouse_code varchar NOT NULL,
    warehouse_name varchar NOT NULL,
    is_default boolean NOT NULL DEFAULT false,
    use_yn boolean NOT NULL DEFAULT true,
    remarks varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_warehouse PRIMARY KEY (id),
    CONSTRAINT uq_bc_warehouse_warehouse_code UNIQUE (warehouse_code)
);
-- At most one default warehouse (MM-BR-702). The warehouse master keeps exactly one
CREATE UNIQUE INDEX uq_bc_warehouse_single_default ON bc_warehouse (is_default) WHERE is_default;

-- The default warehouse made at installation (MM-BR-702). Code and name are placeholders [확인 필요]
