-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- customer: 고객 — AS IS `B_CUSTOMER` (Customer Master)
CREATE TABLE customer (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    c_name varchar(40),
    contact varchar(50),
    contact2 varchar(50),
    fax_no varchar(30),
    email varchar(60),
    valid_flag varchar(1),
    terms varchar(20),
    remarks varchar(200),
    rep varchar(30),
    price_level varchar(40),
    freight_charge varchar(10),
    addr1 varchar(80),
    addr2 varchar(80),
    city varchar(40),
    state varchar(4),
    country varchar(20),
    zip_code varchar(20),
    ship_addr1 varchar(80),
    ship_addr2 varchar(80),
    ship_city varchar(40),
    ship_state varchar(4),
    ship_country varchar(20),
    ship_zip_code varchar(20),
    phone1 varchar(30),
    phone2 varchar(30),
    phone3 varchar(30),
    upload_flag varchar(1),
    merge_flag varchar(1),
    ship_phone varchar(30),
    ship_fax varchar(30),
    credit_limit numeric(15,4),
    dc_status varchar(20),
    start_dt timestamp,
    memo2 varchar(200),
    memo3 varchar(200),
    ship_name varchar(40),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_customer PRIMARY KEY (id),
    CONSTRAINT uq_customer_c_name UNIQUE (c_name)
);

-- discount_rate: 할인율 (codes.md, AS IS 코드 SC00)
CREATE TABLE discount_rate (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    discount_code varchar(20) NOT NULL,
    rate numeric(7,4) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_discount_rate PRIMARY KEY (id),
    CONSTRAINT uq_discount_rate_discount_code UNIQUE (discount_code)
);

-- sales_order: 수주 — AS IS `S_SO_HDR` (Sales Order Header)
CREATE TABLE sales_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    so_no varchar(18),
    status varchar(2),
    customer_id bigint,
    so_dt timestamp,
    exp_ship_dt timestamp,
    tot_so_amt numeric(15,4),
    release_dt timestamp,
    confirm_dt timestamp,
    remarks varchar(200),
    due_dt timestamp,
    rep varchar(30),
    terms varchar(20),
    ship_via varchar(14),
    freight_charge varchar(10),
    ship_addr1 varchar(80),
    ship_addr2 varchar(80),
    ship_city varchar(40),
    ship_state varchar(2),
    ship_country varchar(20),
    ship_zip_code varchar(20),
    upload_flag varchar(1),
    merge_flag varchar(1),
    src_no varchar(18),
    ship_phone varchar(30),
    ship_fax varchar(30),
    ship_name varchar(40),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_sales_order PRIMARY KEY (id),
    CONSTRAINT uq_sales_order_so_no UNIQUE (so_no),
    CONSTRAINT fk_sales_order_customer_id FOREIGN KEY (customer_id) REFERENCES customer (id)
);
CREATE INDEX ix_sales_order_customer_id ON sales_order (customer_id);

-- sales_order_line: 수주 상세 — AS IS `S_SO_DTL` (Sales Order Detail)
CREATE TABLE sales_order_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    sales_order_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    so_qty numeric(15,4),
    so_prc numeric(15,4),
    so_amt numeric(15,4),
    dn_qty numeric(15,4),
    item_name varchar(50),
    dc_cd varchar(10),
    dc_rate numeric(15,4),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_sales_order_line PRIMARY KEY (id),
    CONSTRAINT uq_sales_order_line_sales_order_id_seq UNIQUE (sales_order_id, seq),
    CONSTRAINT fk_sales_order_line_sales_order_id FOREIGN KEY (sales_order_id) REFERENCES sales_order (id) ON DELETE CASCADE,
    CONSTRAINT fk_sales_order_line_item_id FOREIGN KEY (item_id) REFERENCES item (id)
);
CREATE INDEX ix_sales_order_line_item_id ON sales_order_line (item_id);

-- sales_invoice: 매출 송장 — AS IS `S_DN_HDR`
CREATE TABLE sales_invoice (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    dn_no varchar(18),
    customer_id bigint,
    sales_order_id bigint,
    dn_dt timestamp,
    ship_dt timestamp,
    due_dt timestamp,
    tot_dn_amt numeric(15,4),
    remarks varchar(200),
    bal_amt numeric(15,4),
    terms varchar(20),
    type varchar(2),
    rep varchar(30),
    ship_via varchar(14),
    freight_charge varchar(10),
    ship_addr1 varchar(80),
    ship_addr2 varchar(80),
    ship_city varchar(40),
    ship_state varchar(22),
    ship_country varchar(23),
    ship_zip_code varchar(20),
    status varchar(2),
    ship_phone varchar(30),
    ship_fax varchar(30),
    cm_reason01 varchar(1),
    cm_reason02 varchar(1),
    cm_reason03 varchar(1),
    cm_reason04 varchar(1),
    cm_reason05 varchar(1),
    cm_reason06 varchar(1),
    cm_reason07 varchar(1),
    cm_reason08 varchar(1),
    ship_name varchar(40),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_sales_invoice PRIMARY KEY (id),
    CONSTRAINT uq_sales_invoice_dn_no UNIQUE (dn_no),
    CONSTRAINT fk_sales_invoice_customer_id FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT fk_sales_invoice_sales_order_id FOREIGN KEY (sales_order_id) REFERENCES sales_order (id)
);
CREATE INDEX ix_sales_invoice_customer_id ON sales_invoice (customer_id);
CREATE INDEX ix_sales_invoice_sales_order_id ON sales_invoice (sales_order_id);

-- sales_invoice_line: 매출 송장 상세 — AS IS `S_DN_DTL`
CREATE TABLE sales_invoice_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    sales_invoice_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    dn_qty numeric(15,4),
    dn_prc numeric(15,4),
    dn_amt numeric(15,4),
    sales_order_line_id bigint,
    item_name varchar(50),
    dc_cd varchar(10),
    dc_rate numeric(15,4),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_sales_invoice_line PRIMARY KEY (id),
    CONSTRAINT uq_sales_invoice_line_sales_invoice_id_seq UNIQUE (sales_invoice_id, seq),
    CONSTRAINT fk_sales_invoice_line_sales_invoice_id FOREIGN KEY (sales_invoice_id) REFERENCES sales_invoice (id) ON DELETE CASCADE,
    CONSTRAINT fk_sales_invoice_line_item_id FOREIGN KEY (item_id) REFERENCES item (id),
    CONSTRAINT fk_sales_invoice_line_sales_order_line_id FOREIGN KEY (sales_order_line_id) REFERENCES sales_order_line (id)
);
CREATE INDEX ix_sales_invoice_line_item_id ON sales_invoice_line (item_id);
CREATE INDEX ix_sales_invoice_line_sales_order_line_id ON sales_invoice_line (sales_order_line_id);

-- customer_opening_balance: 고객 기초 잔액 — AS IS `S_INIT_BAL`
CREATE TABLE customer_opening_balance (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    customer_id bigint,
    type varchar(2),
    bal_amt numeric(15,4),
    amt numeric(15,4),
    dn_dt timestamp,
    due_dt timestamp,
    no varchar(18),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_customer_opening_balance PRIMARY KEY (id),
    CONSTRAINT uq_customer_opening_balance_no UNIQUE (no),
    CONSTRAINT fk_customer_opening_balance_customer_id FOREIGN KEY (customer_id) REFERENCES customer (id)
);
CREATE INDEX ix_customer_opening_balance_customer_id ON customer_opening_balance (customer_id);

-- sales_order_closing: 수주 마감 이력 — AS IS `S_SO_CLOSE_HIST`
CREATE TABLE sales_order_closing (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    close_dt timestamp,
    from_dt timestamp,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_sales_order_closing PRIMARY KEY (id),
    CONSTRAINT uq_sales_order_closing_close_dt UNIQUE (close_dt)
);
