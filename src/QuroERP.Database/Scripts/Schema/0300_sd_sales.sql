-- sd_discount_rate
CREATE TABLE sd_discount_rate (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    discount_code varchar NOT NULL,
    rate numeric NOT NULL,
    sort_order integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_discount_rate PRIMARY KEY (id),
    CONSTRAINT uq_sd_discount_rate_discount_code UNIQUE (discount_code)
);

-- sd_sales_order: 수주 — AS IS `S_SO_HDR` (Sales Order Header)
CREATE TABLE sd_sales_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    so_no varchar NOT NULL,
    status varchar,
    customer_id bigint,
    so_dt date,
    exp_ship_dt date,
    tot_so_amt numeric,
    release_dt date,
    confirm_dt date,
    remarks varchar,
    due_dt date,
    rep varchar,
    terms varchar,
    ship_via varchar,
    freight_charge varchar,
    ship_addr1 varchar,
    ship_addr2 varchar,
    ship_city varchar,
    ship_state varchar,
    ship_country varchar,
    ship_zip_code varchar,
    upload_flag boolean,
    merge_flag boolean,
    src_no varchar,
    ship_phone varchar,
    ship_fax varchar,
    ship_name varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_sales_order PRIMARY KEY (id),
    CONSTRAINT uq_sd_sales_order_so_no UNIQUE (so_no),
    CONSTRAINT fk_sd_sales_order_customer_id FOREIGN KEY (customer_id) REFERENCES bc_customer (id)
);
CREATE INDEX ix_sd_sales_order_customer_id ON sd_sales_order (customer_id);

-- sd_sales_order_line: 수주 상세 — AS IS `S_SO_DTL` (Sales Order Detail)
CREATE TABLE sd_sales_order_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    sales_order_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    so_qty numeric,
    so_prc numeric,
    so_amt numeric,
    dn_qty numeric,
    item_name varchar,
    dc_cd varchar,
    dc_rate numeric,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_sales_order_line PRIMARY KEY (id),
    CONSTRAINT uq_sd_sales_order_line_sales_order_id_seq UNIQUE (sales_order_id, seq),
    CONSTRAINT fk_sd_sales_order_line_sales_order_id FOREIGN KEY (sales_order_id) REFERENCES sd_sales_order (id) ON DELETE CASCADE,
    CONSTRAINT fk_sd_sales_order_line_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_sd_sales_order_line_item_id ON sd_sales_order_line (item_id);

