-- 회사·채번·화면 설정·환율
-- 정의: docs/architecture/database-tables.md (database.md, codes.md, i18n.md, inventory.md, security.md)
-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- company: 회사 — AS IS `B_COMPANY` (Company)
CREATE TABLE company (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar(40),
    billto varchar(200),
    shipto varchar(200),
    contact varchar(40),
    tel_no varchar(20),
    fax_no varchar(20),
    register_no varchar(30),
    represent varchar(30),
    email varchar(30),
    close_year_month varchar(30),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_company PRIMARY KEY (id),
    CONSTRAINT uq_company_name UNIQUE (name)
);

-- document_number: 문서 번호 채번 — AS IS `B_AUTO_NUM` (Auto Numbering)
CREATE TABLE document_number (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    trans_type varchar(2),
    trans_no varchar(18),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_document_number PRIMARY KEY (id),
    CONSTRAINT uq_document_number_trans_type UNIQUE (trans_type)
);

-- ui_setting: 화면 설정 (codes.md, AS IS 코드 BA00)
CREATE TABLE ui_setting (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    screen_code varchar(50) NOT NULL,
    default_rows integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_ui_setting PRIMARY KEY (id),
    CONSTRAINT uq_ui_setting_screen_code UNIQUE (screen_code)
);

-- exchange_rate: 환율 — AS IS `B_CURRENCY` (Currency Code)
CREATE TABLE exchange_rate (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    cur_dt timestamp,
    cur_rp numeric(15,4),
    cur_won numeric(15,4),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_exchange_rate PRIMARY KEY (id),
    CONSTRAINT uq_exchange_rate_cur_dt UNIQUE (cur_dt)
);
