-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- sys_code_major: Major 코드 — AS IS `B_MAJOR` (Major Code)
CREATE TABLE sys_code_major (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    major_code varchar NOT NULL,
    use_yn boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_code_major PRIMARY KEY (id),
    CONSTRAINT uq_sys_code_major_major_code UNIQUE (major_code)
);

-- sys_code_minor: Minor 코드 — AS IS `B_MINOR` (Minor Code)
CREATE TABLE sys_code_minor (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    major_id bigint,
    minor_code varchar NOT NULL,
    sort_order integer NOT NULL,
    use_yn boolean NOT NULL DEFAULT true,
    attr1 varchar,
    attr2 varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_code_minor PRIMARY KEY (id),
    CONSTRAINT uq_sys_code_minor_major_id_minor_code UNIQUE (major_id, minor_code),
    CONSTRAINT fk_sys_code_minor_major_id FOREIGN KEY (major_id) REFERENCES sys_code_major (id)
);
