-- 대체 품목 그룹·품목·품목 번역·단가·장바구니 (BC)
-- 정의: docs/architecture/database-tables.md (database.md, codes.md, i18n.md, inventory.md, security.md)
-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- bc_alternate_item_group: 대체 품목 그룹 — AS IS `B_ALT_ITEM`
CREATE TABLE bc_alternate_item_group (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    alt_item_group_cd varchar NOT NULL,
    alt_item_group_name varchar,
    class varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_alternate_item_group PRIMARY KEY (id),
    CONSTRAINT uq_bc_alternate_item_group_alt_item_group_cd UNIQUE (alt_item_group_cd)
);

-- bc_item: 품목 — AS IS `B_ITEM` (Item)
CREATE TABLE bc_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    item_cd varchar NOT NULL,
    item_name varchar,
    type varchar,
    unit varchar,
    class varchar,
    valid_flag varchar,
    mvg_cost numeric,
    usd_prc numeric,
    onhand_qty numeric,
    item_desc varchar,
    stk_val numeric,
    so_usd_prc numeric,
    upc_code varchar,
    img bytea,
    location varchar,
    reorder_point numeric,
    sales_mvg_cost numeric,
    memo1 varchar,
    memo2 varchar,
    memo3 varchar,
    plating varchar,
    item_grade varchar,
    item_group_cd varchar,
    alternate_item_group_id bigint,
    item_name2 varchar,
    memo4 varchar,
    memo5 varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_item PRIMARY KEY (id),
    CONSTRAINT uq_bc_item_item_cd UNIQUE (item_cd),
    CONSTRAINT fk_bc_item_alternate_item_group_id FOREIGN KEY (alternate_item_group_id) REFERENCES bc_alternate_item_group (id)
);
CREATE INDEX ix_bc_item_alternate_item_group_id ON bc_item (alternate_item_group_id);

-- bc_item_translation: 품목 번역 (i18n.md). 컬럼: 새 테이블 표의 주요 컬럼
CREATE TABLE bc_item_translation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    item_id bigint NOT NULL,
    lang_code varchar NOT NULL,
    item_name varchar,
    item_desc varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_item_translation PRIMARY KEY (id),
    CONSTRAINT uq_bc_item_translation_item_id_lang_code UNIQUE (item_id, lang_code),
    CONSTRAINT fk_bc_item_translation_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id) ON DELETE CASCADE
);

-- bc_sales_price: 판매 단가 — AS IS `B_PRICE_LEVEL`
CREATE TABLE bc_sales_price (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    price_level varchar NOT NULL,
    item_id bigint,
    sales_prc numeric,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_sales_price PRIMARY KEY (id),
    CONSTRAINT uq_bc_sales_price_price_level_item_id UNIQUE (price_level, item_id),
    CONSTRAINT fk_bc_sales_price_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_bc_sales_price_item_id ON bc_sales_price (item_id);

-- bc_purchase_price: 구매 단가 — AS IS `B_VENDOR_PRICE`
CREATE TABLE bc_purchase_price (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    vendor_price varchar NOT NULL,
    item_id bigint,
    purchase_prc numeric,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_purchase_price PRIMARY KEY (id),
    CONSTRAINT uq_bc_purchase_price_vendor_price_item_id UNIQUE (vendor_price, item_id),
    CONSTRAINT fk_bc_purchase_price_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_bc_purchase_price_item_id ON bc_purchase_price (item_id);

-- bc_cart_item: 장바구니 — AS IS `B_CART`
CREATE TABLE bc_cart_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    app_user_id bigint,
    cart_no integer NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    qty numeric,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_cart_item PRIMARY KEY (id),
    CONSTRAINT uq_bc_cart_item_app_user_id_cart_no_seq UNIQUE (app_user_id, cart_no, seq),
    CONSTRAINT fk_bc_cart_item_app_user_id FOREIGN KEY (app_user_id) REFERENCES sys_app_user (id),
    CONSTRAINT fk_bc_cart_item_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_bc_cart_item_item_id ON bc_cart_item (item_id);
