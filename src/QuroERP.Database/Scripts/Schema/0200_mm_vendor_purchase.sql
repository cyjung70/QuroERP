-- 공급자·구매 시뮬레이션·발주·입고 (MM)
-- 정의: docs/architecture/database-tables.md (database.md, codes.md, i18n.md, inventory.md, security.md)
-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- vendor: 공급자 — AS IS `B_VENDOR` (Vendor Master)
CREATE TABLE vendor (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    v_name varchar(40),
    contact varchar(50),
    contact2 varchar(50),
    fax_no varchar(18),
    email varchar(30),
    valid_flag varchar(1),
    terms varchar(20),
    remarks varchar(200),
    addr1 varchar(80),
    addr2 varchar(80),
    city varchar(40),
    state varchar(4),
    country varchar(20),
    zip_code varchar(20),
    ship_addr1 varchar(80),
    ship_addr2 varchar(80),
    ship_city varchar(40),
    ship_state varchar(4),
    ship_country varchar(20),
    ship_zip_code varchar(20),
    phone1 varchar(18),
    phone2 varchar(18),
    phone3 varchar(18),
    vendor_price varchar(40),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_vendor PRIMARY KEY (id),
    CONSTRAINT uq_vendor_v_name UNIQUE (v_name)
);

-- purchase_simulation: 구매 시뮬레이션 — AS IS `M_PS_HDR`
CREATE TABLE purchase_simulation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    ps_no varchar(18),
    ps_dt timestamp,
    remarks varchar(200),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_purchase_simulation PRIMARY KEY (id),
    CONSTRAINT uq_purchase_simulation_ps_no UNIQUE (ps_no)
);

-- purchase_simulation_line: 구매 시뮬레이션 상세 — AS IS `M_PS_DTL`
CREATE TABLE purchase_simulation_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    purchase_simulation_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    m2_qty numeric(15,4),
    m1_qty numeric(15,4),
    m0_qty numeric(15,4),
    open_so_qty numeric(15,4),
    rop_qty numeric(15,4),
    onhand_qty numeric(15,4),
    estimated_po_qty numeric(15,4),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_purchase_simulation_line PRIMARY KEY (id),
    CONSTRAINT uq_purchase_simulation_line_purchase_simulation_id_seq UNIQUE (purchase_simulation_id, seq),
    CONSTRAINT fk_purchase_simulation_line_purchase_simulation_id FOREIGN KEY (purchase_simulation_id) REFERENCES purchase_simulation (id) ON DELETE CASCADE,
    CONSTRAINT fk_purchase_simulation_line_item_id FOREIGN KEY (item_id) REFERENCES item (id)
);
CREATE INDEX ix_purchase_simulation_line_item_id ON purchase_simulation_line (item_id);

-- purchase_order: 발주 — AS IS `M_PO_HDR` (Purchase Order Header)
CREATE TABLE purchase_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    po_no varchar(18),
    status varchar(2),
    vendor_id bigint,
    po_dt timestamp,
    tot_po_amt numeric(15,4),
    release_dt timestamp,
    confirm_dt timestamp,
    remarks varchar(200),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_purchase_order PRIMARY KEY (id),
    CONSTRAINT uq_purchase_order_po_no UNIQUE (po_no),
    CONSTRAINT fk_purchase_order_vendor_id FOREIGN KEY (vendor_id) REFERENCES vendor (id)
);
CREATE INDEX ix_purchase_order_vendor_id ON purchase_order (vendor_id);

-- purchase_order_line: 발주 상세 — AS IS `M_PO_DTL` (Purchase Order Detail)
CREATE TABLE purchase_order_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    purchase_order_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    po_qty numeric(15,4),
    po_prc numeric(15,4),
    po_amt numeric(15,4),
    receipt_qty numeric(15,4),
    item_name varchar(40),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_purchase_order_line PRIMARY KEY (id),
    CONSTRAINT uq_purchase_order_line_purchase_order_id_seq UNIQUE (purchase_order_id, seq),
    CONSTRAINT fk_purchase_order_line_purchase_order_id FOREIGN KEY (purchase_order_id) REFERENCES purchase_order (id) ON DELETE CASCADE,
    CONSTRAINT fk_purchase_order_line_item_id FOREIGN KEY (item_id) REFERENCES item (id)
);
CREATE INDEX ix_purchase_order_line_item_id ON purchase_order_line (item_id);

-- goods_receipt: 입고 — AS IS `M_GR_HDR` (Goods Receipt Header)
CREATE TABLE goods_receipt (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    gr_no varchar(18),
    vendor_id bigint,
    gr_dt timestamp,
    ref_no varchar(18),
    tot_gr_amt numeric(15,4),
    due_dt timestamp,
    cls_amt numeric(15,4),
    bal_amt numeric(15,4),
    type varchar(10),
    remarks varchar(200),
    terms varchar(20),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_goods_receipt PRIMARY KEY (id),
    CONSTRAINT uq_goods_receipt_gr_no UNIQUE (gr_no),
    CONSTRAINT fk_goods_receipt_vendor_id FOREIGN KEY (vendor_id) REFERENCES vendor (id)
);
CREATE INDEX ix_goods_receipt_vendor_id ON goods_receipt (vendor_id);

-- goods_receipt_line: 입고 상세 — AS IS `M_GR_DTL` (Goods Receipt Detail)
CREATE TABLE goods_receipt_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    goods_receipt_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    gr_qty numeric(15,4),
    gr_prc numeric(15,4),
    gr_amt numeric(15,4),
    purchase_order_line_id bigint,
    item_name varchar(40),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_goods_receipt_line PRIMARY KEY (id),
    CONSTRAINT uq_goods_receipt_line_goods_receipt_id_seq UNIQUE (goods_receipt_id, seq),
    CONSTRAINT fk_goods_receipt_line_goods_receipt_id FOREIGN KEY (goods_receipt_id) REFERENCES goods_receipt (id) ON DELETE CASCADE,
    CONSTRAINT fk_goods_receipt_line_item_id FOREIGN KEY (item_id) REFERENCES item (id),
    CONSTRAINT fk_goods_receipt_line_purchase_order_line_id FOREIGN KEY (purchase_order_line_id) REFERENCES purchase_order_line (id)
);
CREATE INDEX ix_goods_receipt_line_item_id ON goods_receipt_line (item_id);
CREATE INDEX ix_goods_receipt_line_purchase_order_line_id ON goods_receipt_line (purchase_order_line_id);
