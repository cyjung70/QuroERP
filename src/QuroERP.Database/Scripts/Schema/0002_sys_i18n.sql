-- sys_code_major_translation
CREATE TABLE sys_code_major_translation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    major_id bigint NOT NULL,
    lang_code varchar NOT NULL,
    name varchar NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_code_major_translation PRIMARY KEY (id),
    CONSTRAINT uq_sys_code_major_translation_major_id_lang_code UNIQUE (major_id, lang_code),
    CONSTRAINT fk_sys_code_major_translation_major_id FOREIGN KEY (major_id) REFERENCES sys_code_major (id) ON DELETE CASCADE
);

-- sys_code_minor_translation
CREATE TABLE sys_code_minor_translation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    minor_id bigint NOT NULL,
    lang_code varchar NOT NULL,
    name varchar NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_code_minor_translation PRIMARY KEY (id),
    CONSTRAINT uq_sys_code_minor_translation_minor_id_lang_code UNIQUE (minor_id, lang_code),
    CONSTRAINT fk_sys_code_minor_translation_minor_id FOREIGN KEY (minor_id) REFERENCES sys_code_minor (id) ON DELETE CASCADE
);
