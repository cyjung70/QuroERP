-- goods_issue_line: 출고(불출) 상세 — AS IS `M_GI_DTL` (Goods Issue Detail)
CREATE TABLE goods_issue_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    goods_issue_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    gi_qty numeric(15,4),
    gi_unit varchar(5),
    gi_prc numeric(15,4),
    gi_amt numeric(15,4),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_goods_issue_line PRIMARY KEY (id),
    CONSTRAINT uq_goods_issue_line_goods_issue_id_seq UNIQUE (goods_issue_id, seq),
    CONSTRAINT fk_goods_issue_line_goods_issue_id FOREIGN KEY (goods_issue_id) REFERENCES goods_issue (id) ON DELETE CASCADE,
    CONSTRAINT fk_goods_issue_line_item_id FOREIGN KEY (item_id) REFERENCES item (id)
);
CREATE INDEX ix_goods_issue_line_item_id ON goods_issue_line (item_id);

