-- 문서 번호 채번·화면 설정
-- 정의: docs/architecture/database-tables.md (database.md, codes.md, i18n.md, inventory.md, security.md)
-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- sys_document_number: 문서 번호 채번 — AS IS `B_AUTO_NUM` (Auto Numbering)
CREATE TABLE sys_document_number (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    trans_type varchar NOT NULL,
    trans_no varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_document_number PRIMARY KEY (id),
    CONSTRAINT uq_sys_document_number_trans_type UNIQUE (trans_type)
);

-- sys_ui_setting
CREATE TABLE sys_ui_setting (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    screen_code varchar NOT NULL,
    default_rows integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sys_ui_setting PRIMARY KEY (id),
    CONSTRAINT uq_sys_ui_setting_screen_code UNIQUE (screen_code)
);
