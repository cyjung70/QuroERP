    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_code_minor_translation PRIMARY KEY (id),
    CONSTRAINT uq_code_minor_translation_minor_id_lang_code UNIQUE (minor_id, lang_code),
    CONSTRAINT fk_code_minor_translation_minor_id FOREIGN KEY (minor_id) REFERENCES code_minor (id) ON DELETE CASCADE
