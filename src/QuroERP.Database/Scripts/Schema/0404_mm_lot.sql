-- Lots and lot balances (TASK-CORE-027)
-- Definition: database-tables.md (mm_lot, mm_lot_onhand, mm_goods_movement.lot_id, bc_item.lot_managed), MM lot.md, inventory.md "로트"
--   A lot-managed item keeps its stock per item + warehouse + lot as well; mm_onhand = the sum of its lot balances (MM-BR-354).
--   Items start without lot management, so no rows are moved here: turning it on moves the stock to lot MIGRATED (MM-BR-351).
-- Applied scripts are never edited. Add a new numbered script for changes.

-- bc_item: lot management and the day it was turned on (MM-BR-351, MM-BR-356)
ALTER TABLE bc_item
    ADD COLUMN lot_managed boolean NOT NULL DEFAULT false,
    ADD COLUMN lot_managed_from date;

-- mm_lot: one row per item + lot number; upper case letters, digits, '-' and '_', up to 30 characters (MM-BR-352)
CREATE TABLE mm_lot (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    item_id bigint NOT NULL,
    lot_no varchar NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_lot PRIMARY KEY (id),
    CONSTRAINT uq_mm_lot_item_id_lot_no UNIQUE (item_id, lot_no),
    CONSTRAINT ck_mm_lot_lot_no CHECK (lot_no ~ '^[A-Z0-9_-]{1,30}$'),
    CONSTRAINT fk_mm_lot_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);

-- mm_lot_onhand: balance per item + warehouse + lot, never below zero (MM-BR-354, MM-BR-356)
CREATE TABLE mm_lot_onhand (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    item_id bigint NOT NULL,
    warehouse_id bigint NOT NULL,
    lot_id bigint NOT NULL,
    onhand_qty numeric NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_lot_onhand PRIMARY KEY (id),
    CONSTRAINT uq_mm_lot_onhand_item_id_warehouse_id_lot_id UNIQUE (item_id, warehouse_id, lot_id),
    CONSTRAINT ck_mm_lot_onhand_onhand_qty CHECK (onhand_qty >= 0),
    CONSTRAINT fk_mm_lot_onhand_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id),
    CONSTRAINT fk_mm_lot_onhand_warehouse_id FOREIGN KEY (warehouse_id) REFERENCES bc_warehouse (id),
    CONSTRAINT fk_mm_lot_onhand_lot_id FOREIGN KEY (lot_id) REFERENCES mm_lot (id)
);
CREATE INDEX ix_mm_lot_onhand_warehouse_id ON mm_lot_onhand (warehouse_id);
CREATE INDEX ix_mm_lot_onhand_lot_id ON mm_lot_onhand (lot_id);

-- mm_goods_movement.lot_id: the lot of a lot-managed item's movement; a reversal keeps the original lot (MM-BR-354, MM-BR-355)
ALTER TABLE mm_goods_movement
    ADD COLUMN lot_id bigint,
    ADD CONSTRAINT fk_mm_goods_movement_lot_id FOREIGN KEY (lot_id) REFERENCES mm_lot (id);
CREATE INDEX ix_mm_goods_movement_lot_id ON mm_goods_movement (lot_id);
CREATE INDEX ix_mm_goods_movement_item_id_warehouse_id_lot_id_document_dt ON mm_goods_movement (item_id, warehouse_id, lot_id, document_dt);
