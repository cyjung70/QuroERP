-- AR receipts (SD-BR-701~713) and credit memo application (SD-BR-251~258). DDL only, as defined in
-- docs/architecture/database-tables.md (TASK-CORE-010, DB-IT-03)
-- Applied scripts are never edited. Add a new numbered script for changes.

-- sd_ar_receipt: AR receipt — AS IS `A_AR_RECEIPT` (A/R Receipt Header)
CREATE TABLE sd_ar_receipt (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    cls_ar_no varchar NOT NULL,
    customer_id bigint,
    total_amt numeric NOT NULL DEFAULT 0,
    cls_dt date NOT NULL,
    pay_method varchar NOT NULL,
    remarks varchar,
    ref_no varchar,
    dc_amt numeric NOT NULL DEFAULT 0,
    receive_amt numeric NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_ar_receipt PRIMARY KEY (id),
    CONSTRAINT uq_sd_ar_receipt_cls_ar_no UNIQUE (cls_ar_no),
    CONSTRAINT fk_sd_ar_receipt_customer_id FOREIGN KEY (customer_id) REFERENCES bc_customer (id)
);
CREATE INDEX ix_sd_ar_receipt_customer_id_cls_dt ON sd_ar_receipt (customer_id, cls_dt);

-- sd_ar_clear: AR receipt line — AS IS `A_AR_CLS` (A/R Receipt Detail)
CREATE TABLE sd_ar_clear (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    ar_receipt_id bigint,
    seq integer NOT NULL,
    sales_invoice_id bigint,
    cls_dt date NOT NULL,
    cls_amt numeric NOT NULL DEFAULT 0,
    dc_amt numeric NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_ar_clear PRIMARY KEY (id),
    CONSTRAINT uq_sd_ar_clear_ar_receipt_id_sales_invoice_id UNIQUE (ar_receipt_id, sales_invoice_id),
    CONSTRAINT fk_sd_ar_clear_ar_receipt_id FOREIGN KEY (ar_receipt_id) REFERENCES sd_ar_receipt (id),
    CONSTRAINT fk_sd_ar_clear_sales_invoice_id FOREIGN KEY (sales_invoice_id) REFERENCES sd_sales_invoice (id)
);
CREATE INDEX ix_sd_ar_clear_sales_invoice_id ON sd_ar_clear (sales_invoice_id);

-- sd_cm_apply: credit memo application — AS IS `A_AC_HDR`
CREATE TABLE sd_cm_apply (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    sales_invoice_id bigint,
    total_amt numeric NOT NULL DEFAULT 0,
    cls_dt date NOT NULL,
    apply_flag varchar NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_cm_apply PRIMARY KEY (id),
    CONSTRAINT uq_sd_cm_apply_sales_invoice_id_apply_flag UNIQUE (sales_invoice_id, apply_flag),
    CONSTRAINT fk_sd_cm_apply_sales_invoice_id FOREIGN KEY (sales_invoice_id) REFERENCES sd_sales_invoice (id)
);

-- sd_cm_clear: credit memo application line — AS IS `A_AC_DTL`
CREATE TABLE sd_cm_clear (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    cm_apply_id bigint,
    credit_memo_id bigint NOT NULL,
    cls_dt date NOT NULL,
    cls_amt numeric NOT NULL,
    credit_amt numeric NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_sd_cm_clear PRIMARY KEY (id),
    CONSTRAINT uq_sd_cm_clear_cm_apply_id_credit_memo_id UNIQUE (cm_apply_id, credit_memo_id),
    CONSTRAINT fk_sd_cm_clear_cm_apply_id FOREIGN KEY (cm_apply_id) REFERENCES sd_cm_apply (id),
    CONSTRAINT fk_sd_cm_clear_credit_memo_id FOREIGN KEY (credit_memo_id) REFERENCES sd_sales_invoice (id)
);
CREATE INDEX ix_sd_cm_clear_credit_memo_id ON sd_cm_clear (credit_memo_id);
