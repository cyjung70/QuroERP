-- bc_customer: 고객 — AS IS `B_CUSTOMER` (Customer Master)
CREATE TABLE bc_customer (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    c_name varchar NOT NULL,
    contact varchar,
    contact2 varchar,
    fax_no varchar,
    email varchar,
    valid_flag varchar,
    terms varchar,
    remarks varchar,
    rep varchar,
    price_level varchar,
    freight_charge varchar,
    addr1 varchar,
    addr2 varchar,
    city varchar,
    state varchar,
    country varchar,
    zip_code varchar,
    ship_addr1 varchar,
    ship_addr2 varchar,
    ship_city varchar,
    ship_state varchar,
    ship_country varchar,
    ship_zip_code varchar,
    phone1 varchar,
    phone2 varchar,
    phone3 varchar,
    upload_flag boolean,
    merge_flag boolean,
    ship_phone varchar,
    ship_fax varchar,
    credit_limit numeric,
    dc_status varchar,
    start_dt date,
    memo2 varchar,
    memo3 varchar,
    ship_name varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_customer PRIMARY KEY (id),
    CONSTRAINT uq_bc_customer_c_name UNIQUE (c_name)
);

-- bc_vendor: 공급자 — AS IS `B_VENDOR` (Vendor Master)
CREATE TABLE bc_vendor (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    v_name varchar NOT NULL,
    contact varchar,
    contact2 varchar,
    fax_no varchar,
    email varchar,
    valid_flag varchar,
    terms varchar,
    remarks varchar,
    addr1 varchar,
    addr2 varchar,
    city varchar,
    state varchar,
    country varchar,
    zip_code varchar,
    ship_addr1 varchar,
    ship_addr2 varchar,
    ship_city varchar,
    ship_state varchar,
    ship_country varchar,
    ship_zip_code varchar,
    phone1 varchar,
    phone2 varchar,
    phone3 varchar,
    vendor_price varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_vendor PRIMARY KEY (id),
    CONSTRAINT uq_bc_vendor_v_name UNIQUE (v_name)
);
