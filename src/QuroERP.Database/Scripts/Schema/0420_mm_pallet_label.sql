-- Pallet and label foundation (TASK-CORE-070)
-- Definition: database-tables.md (mm_pallet, mm_pallet_event, bc_label_format, mm_label_print, Pallet columns of the stock
--   documents), inventory.md "Pallet·라벨", MM pallet.md (MM-BR-910~919)
--   A Pallet is one item and one Lot in one warehouse and Location (MM-BR-911). The stock key has no Pallet: the Pallet quantity
--   lives in mm_pallet, and the ACTIVE Pallets of a key never hold more than its balance (MM-BR-916).
--   Every step checks what is already there, so the script gives the same schema when it runs again.
-- Applied scripts are never edited. Add a new numbered script for changes.

-- mm_pallet: Pallet number PL + yymm + 6 digits (MM-BR-910), quantity >= 0 and CLOSED at 0 (MM-BR-911)
CREATE TABLE IF NOT EXISTS mm_pallet (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    pallet_no varchar NOT NULL,
    item_id bigint NOT NULL,
    lot_id bigint NOT NULL,
    warehouse_id bigint NOT NULL,
    location_id bigint NOT NULL,
    qty numeric NOT NULL,
    status varchar NOT NULL DEFAULT 'ACTIVE',
    goods_receipt_line_id bigint,
    parent_pallet_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_pallet PRIMARY KEY (id),
    CONSTRAINT uq_mm_pallet_pallet_no UNIQUE (pallet_no),
    CONSTRAINT ck_mm_pallet_qty CHECK (qty >= 0),
    CONSTRAINT ck_mm_pallet_status CHECK (status IN ('ACTIVE', 'CLOSED')),
    CONSTRAINT ck_mm_pallet_closed_at_zero CHECK (status = 'CLOSED' OR qty > 0),
    CONSTRAINT fk_mm_pallet_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id),
    CONSTRAINT fk_mm_pallet_lot_id FOREIGN KEY (lot_id) REFERENCES mm_lot (id),
    CONSTRAINT fk_mm_pallet_warehouse_id FOREIGN KEY (warehouse_id) REFERENCES bc_warehouse (id),
    CONSTRAINT fk_mm_pallet_location_id FOREIGN KEY (location_id) REFERENCES bc_location (id),
    CONSTRAINT fk_mm_pallet_goods_receipt_line_id FOREIGN KEY (goods_receipt_line_id) REFERENCES mm_goods_receipt_line (id),
    CONSTRAINT fk_mm_pallet_parent_pallet_id FOREIGN KEY (parent_pallet_id) REFERENCES mm_pallet (id)
);
-- The stock key comes first: the MM-BR-916 check and the FIFO suggestion sum the ACTIVE Pallets of one key
CREATE INDEX IF NOT EXISTS ix_mm_pallet_item_id ON mm_pallet (item_id, warehouse_id, location_id, lot_id);
CREATE INDEX IF NOT EXISTS ix_mm_pallet_lot_id ON mm_pallet (lot_id);
CREATE INDEX IF NOT EXISTS ix_mm_pallet_warehouse_id ON mm_pallet (warehouse_id);
CREATE INDEX IF NOT EXISTS ix_mm_pallet_location_id ON mm_pallet (location_id);
CREATE INDEX IF NOT EXISTS ix_mm_pallet_goods_receipt_line_id ON mm_pallet (goods_receipt_line_id);
CREATE INDEX IF NOT EXISTS ix_mm_pallet_parent_pallet_id ON mm_pallet (parent_pallet_id);

-- mm_pallet_event: what happened to a Pallet (MM-BR-916)
CREATE TABLE IF NOT EXISTS mm_pallet_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    pallet_id bigint NOT NULL,
    event_type varchar NOT NULL,
    event_dt date NOT NULL,
    qty numeric NOT NULL,
    related_pallet_id bigint,
    ref_key varchar,
    ref_seq integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_pallet_event PRIMARY KEY (id),
    CONSTRAINT ck_mm_pallet_event_event_type CHECK (event_type IN ('CREATE', 'MOVE', 'SHIP', 'SPLIT', 'MERGE', 'ADJUST')),
    CONSTRAINT fk_mm_pallet_event_pallet_id FOREIGN KEY (pallet_id) REFERENCES mm_pallet (id),
    CONSTRAINT fk_mm_pallet_event_related_pallet_id FOREIGN KEY (related_pallet_id) REFERENCES mm_pallet (id)
);
CREATE INDEX IF NOT EXISTS ix_mm_pallet_event_pallet_id ON mm_pallet_event (pallet_id);
CREATE INDEX IF NOT EXISTS ix_mm_pallet_event_related_pallet_id ON mm_pallet_event (related_pallet_id);

-- bc_label_format: one format per label type, ZPL or PDF, size, resolution and the printed fields in order (MM-BR-917)
CREATE TABLE IF NOT EXISTS bc_label_format (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    label_type varchar NOT NULL,
    output_kind varchar NOT NULL,
    width_mm numeric NOT NULL,
    height_mm numeric NOT NULL,
    dpi integer NOT NULL,
    fields jsonb NOT NULL DEFAULT '[]',
    use_yn boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_label_format PRIMARY KEY (id),
    CONSTRAINT uq_bc_label_format_label_type UNIQUE (label_type),
    CONSTRAINT ck_bc_label_format_label_type CHECK (label_type IN ('PALLET', 'ITEM', 'LOT', 'LOCATION')),
    CONSTRAINT ck_bc_label_format_output_kind CHECK (output_kind IN ('ZPL', 'PDF')),
    CONSTRAINT ck_bc_label_format_size CHECK (width_mm > 0 AND height_mm > 0 AND dpi > 0),
    CONSTRAINT ck_bc_label_format_fields CHECK (jsonb_typeof(fields) = 'array')
);

-- mm_label_print: every print, which can be printed again (MM-BR-919)
CREATE TABLE IF NOT EXISTS mm_label_print (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    label_type varchar NOT NULL,
    ref_id bigint NOT NULL,
    copies integer NOT NULL,
    output_kind varchar NOT NULL,
    printer_name varchar,
    printed_at timestamptz NOT NULL DEFAULT now(),
    printed_by varchar NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_label_print PRIMARY KEY (id),
    CONSTRAINT ck_mm_label_print_label_type CHECK (label_type IN ('PALLET', 'ITEM', 'LOT', 'LOCATION')),
    CONSTRAINT ck_mm_label_print_output_kind CHECK (output_kind IN ('ZPL', 'PDF')),
    CONSTRAINT ck_mm_label_print_copies CHECK (copies > 0)
);
CREATE INDEX IF NOT EXISTS ix_mm_label_print_label_type ON mm_label_print (label_type, ref_id);

