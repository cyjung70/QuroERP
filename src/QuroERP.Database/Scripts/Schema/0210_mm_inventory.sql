    item_id bigint,
    bas_qty numeric(15,4),
    bas_amt numeric(15,4),
    rcpt_qty numeric(15,4),
    rcpt_amt numeric(15,4),
    issue_qty numeric(15,4),
    issue_amt numeric(15,4),
    bal_qty numeric(15,4),
    bal_amt numeric(15,4),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_monthly_inventory PRIMARY KEY (id),
    CONSTRAINT uq_monthly_inventory_year_month_item_id UNIQUE (year_month, item_id),
    CONSTRAINT fk_monthly_inventory_item_id FOREIGN KEY (item_id) REFERENCES item (id)
);
CREATE INDEX ix_monthly_inventory_item_id ON monthly_inventory (item_id);

-- inventory_setting: 재고 설정 (inventory.md)
CREATE TABLE inventory_setting (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    company_id bigint NOT NULL,
    plant_id bigint,
    warehouse_id bigint,
    allow_negative_stock boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_inventory_setting PRIMARY KEY (id),
    CONSTRAINT uq_inventory_setting_company_id_plant_id_warehouse_id UNIQUE NULLS NOT DISTINCT (company_id, plant_id, warehouse_id),
    CONSTRAINT fk_inventory_setting_company_id FOREIGN KEY (company_id) REFERENCES company (id)
);
