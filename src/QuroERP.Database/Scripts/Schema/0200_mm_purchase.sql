-- 구매 시뮬레이션·발주·입고 (MM)
-- 정의: docs/architecture/database-tables.md (database.md, codes.md, i18n.md, inventory.md, security.md)
-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- mm_purchase_simulation: 구매 시뮬레이션 — AS IS `M_PS_HDR`
CREATE TABLE mm_purchase_simulation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    ps_no varchar NOT NULL,
    ps_dt date,
    remarks varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_purchase_simulation PRIMARY KEY (id),
    CONSTRAINT uq_mm_purchase_simulation_ps_no UNIQUE (ps_no)
);

-- mm_purchase_simulation_line: 구매 시뮬레이션 상세 — AS IS `M_PS_DTL`
CREATE TABLE mm_purchase_simulation_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    purchase_simulation_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    m2_qty numeric,
    m1_qty numeric,
    m0_qty numeric,
    open_so_qty numeric,
    rop_qty numeric,
    onhand_qty numeric,
    estimated_po_qty numeric,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_purchase_simulation_line PRIMARY KEY (id),
    CONSTRAINT uq_mm_purchase_simulation_line_purchase_simulation_id_seq UNIQUE (purchase_simulation_id, seq),
    CONSTRAINT fk_mm_purchase_simulation_line_purchase_simulation_id FOREIGN KEY (purchase_simulation_id) REFERENCES mm_purchase_simulation (id) ON DELETE CASCADE,
    CONSTRAINT fk_mm_purchase_simulation_line_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_mm_purchase_simulation_line_item_id ON mm_purchase_simulation_line (item_id);

-- mm_purchase_order: 발주 — AS IS `M_PO_HDR` (Purchase Order Header)
CREATE TABLE mm_purchase_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    po_no varchar NOT NULL,
    status varchar,
    vendor_id bigint,
    po_dt date,
    tot_po_amt numeric,
    release_dt date,
    confirm_dt date,
    remarks varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_purchase_order PRIMARY KEY (id),
    CONSTRAINT uq_mm_purchase_order_po_no UNIQUE (po_no),
    CONSTRAINT fk_mm_purchase_order_vendor_id FOREIGN KEY (vendor_id) REFERENCES bc_vendor (id)
);
CREATE INDEX ix_mm_purchase_order_vendor_id ON mm_purchase_order (vendor_id);

-- mm_purchase_order_line: 발주 상세 — AS IS `M_PO_DTL` (Purchase Order Detail)
CREATE TABLE mm_purchase_order_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    purchase_order_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    po_qty numeric,
    po_prc numeric,
    po_amt numeric,
    receipt_qty numeric,
    item_name varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_purchase_order_line PRIMARY KEY (id),
    CONSTRAINT uq_mm_purchase_order_line_purchase_order_id_seq UNIQUE (purchase_order_id, seq),
    CONSTRAINT fk_mm_purchase_order_line_purchase_order_id FOREIGN KEY (purchase_order_id) REFERENCES mm_purchase_order (id) ON DELETE CASCADE,
    CONSTRAINT fk_mm_purchase_order_line_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id)
);
CREATE INDEX ix_mm_purchase_order_line_item_id ON mm_purchase_order_line (item_id);

-- mm_goods_receipt: 입고 — AS IS `M_GR_HDR` (Goods Receipt Header)
CREATE TABLE mm_goods_receipt (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    gr_no varchar NOT NULL,
    vendor_id bigint,
    gr_dt date,
    ref_no varchar,
    tot_gr_amt numeric,
    due_dt date,
    cls_amt numeric,
    bal_amt numeric,
    type varchar,
    remarks varchar,
    terms varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_goods_receipt PRIMARY KEY (id),
    CONSTRAINT uq_mm_goods_receipt_gr_no UNIQUE (gr_no),
    CONSTRAINT fk_mm_goods_receipt_vendor_id FOREIGN KEY (vendor_id) REFERENCES bc_vendor (id)
);
CREATE INDEX ix_mm_goods_receipt_vendor_id ON mm_goods_receipt (vendor_id);

-- mm_goods_receipt_line: 입고 상세 — AS IS `M_GR_DTL` (Goods Receipt Detail)
CREATE TABLE mm_goods_receipt_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    goods_receipt_id bigint NOT NULL,
    seq integer NOT NULL,
    item_id bigint,
    gr_qty numeric,
    gr_prc numeric,
    gr_amt numeric,
    purchase_order_line_id bigint,
    item_name varchar,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_mm_goods_receipt_line PRIMARY KEY (id),
    CONSTRAINT uq_mm_goods_receipt_line_goods_receipt_id_seq UNIQUE (goods_receipt_id, seq),
    CONSTRAINT fk_mm_goods_receipt_line_goods_receipt_id FOREIGN KEY (goods_receipt_id) REFERENCES mm_goods_receipt (id) ON DELETE CASCADE,
    CONSTRAINT fk_mm_goods_receipt_line_item_id FOREIGN KEY (item_id) REFERENCES bc_item (id),
    CONSTRAINT fk_mm_goods_receipt_line_purchase_order_line_id FOREIGN KEY (purchase_order_line_id) REFERENCES mm_purchase_order_line (id)
);
CREATE INDEX ix_mm_goods_receipt_line_item_id ON mm_goods_receipt_line (item_id);
CREATE INDEX ix_mm_goods_receipt_line_purchase_order_line_id ON mm_goods_receipt_line (purchase_order_line_id);
