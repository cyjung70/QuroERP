-- bc_country_decimal: unit price decimals per country and module, a BC global table (localization.md,
--   BC localization.md BC-BR-422, BC-BR-429, TASK-CORE-019). Rows for every supported country, whatever
--   the company country (ICountryProfile.DefaultUnitPriceDecimals).
-- bc_currency.country_code: country of a currency, NULL allowed (BC-BR-428). USD = US, KRW = KR.
-- sys_decimal_setting.unit_price_decimals is moved here and dropped by Seed 0600, after Seed 0504 that
--   still writes it on a new database.
-- Applied scripts are never edited. Add a new numbered script for changes.

CREATE TABLE bc_country_decimal (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    country_code varchar NOT NULL,
    module varchar NOT NULL,
    unit_price_decimals integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar NOT NULL,
    CONSTRAINT pk_bc_country_decimal PRIMARY KEY (id),
    CONSTRAINT uq_bc_country_decimal_country_code_module UNIQUE (country_code, module),
    CONSTRAINT ck_bc_country_decimal_country_code CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_bc_country_decimal_module CHECK (module IN ('MM', 'SD')),
    CONSTRAINT ck_bc_country_decimal_unit_price_decimals CHECK (unit_price_decimals BETWEEN 0 AND 6)
);

