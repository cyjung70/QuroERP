-- 품목·단가·장바구니 (BC)
-- 정의: docs/architecture/database-tables.md (database.md, codes.md, i18n.md, inventory.md, security.md)
-- 적용된 스크립트는 고치지 않는다. 바꿀 것은 새 번호의 스크립트로 추가한다.

-- alternate_item_group: 대체 품목 그룹 — AS IS `B_ALT_ITEM`
CREATE TABLE alternate_item_group (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    alt_item_group_cd varchar(18),
    alt_item_group_name varchar(50),
    class varchar(16),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_alternate_item_group PRIMARY KEY (id),
    CONSTRAINT uq_alternate_item_group_alt_item_group_cd UNIQUE (alt_item_group_cd)
);

-- item: 품목 — AS IS `B_ITEM` (Item)
CREATE TABLE item (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    item_cd varchar(18),
    item_name varchar(50),
    type varchar(10),
    unit varchar(5),
    class varchar(16),
    valid_flag varchar(1),
    mvg_cost numeric(15,4),
    usd_prc numeric(15,4),
    onhand_qty numeric(15,4),
    item_desc varchar(40),
    stk_val numeric(15,4),
    so_usd_prc numeric(15,4),
    upc_code varchar(20),
    img bytea,
    location varchar(15),
    reorder_point numeric(15,4),
    sales_mvg_cost numeric(15,4),
    memo1 varchar(50),
    memo2 varchar(50),
    memo3 varchar(50),
    plating varchar(10),
    item_grade varchar(10),
    item_group_cd varchar(18),
    alternate_item_group_id bigint,
    item_name2 varchar(50),
    memo4 varchar(50),
    memo5 varchar(50),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_item PRIMARY KEY (id),
    CONSTRAINT uq_item_item_cd UNIQUE (item_cd),
    CONSTRAINT fk_item_alternate_item_group_id FOREIGN KEY (alternate_item_group_id) REFERENCES alternate_item_group (id)
);
CREATE INDEX ix_item_alternate_item_group_id ON item (alternate_item_group_id);

-- item_translation: 품목 번역 (i18n.md)
CREATE TABLE item_translation (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    item_id bigint NOT NULL,
    lang_code varchar(10) NOT NULL,
    item_name varchar(50),
    item_desc varchar(40),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_item_translation PRIMARY KEY (id),
    CONSTRAINT uq_item_translation_item_id_lang_code UNIQUE (item_id, lang_code),
    CONSTRAINT fk_item_translation_item_id FOREIGN KEY (item_id) REFERENCES item (id) ON DELETE CASCADE
);

-- sales_price: 판매 단가 — AS IS `B_PRICE_LEVEL`
CREATE TABLE sales_price (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    price_level varchar(40),
    item_id bigint,
    sales_prc numeric(15,4),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_sales_price PRIMARY KEY (id),
    CONSTRAINT uq_sales_price_price_level_item_id UNIQUE (price_level, item_id),
    CONSTRAINT fk_sales_price_item_id FOREIGN KEY (item_id) REFERENCES item (id)
);
CREATE INDEX ix_sales_price_item_id ON sales_price (item_id);

-- purchase_price: 구매 단가 — AS IS `B_VENDOR_PRICE`
CREATE TABLE purchase_price (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    vendor_price varchar(40),
    item_id bigint,
    purchase_prc numeric(15,4),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_purchase_price PRIMARY KEY (id),
    CONSTRAINT uq_purchase_price_vendor_price_item_id UNIQUE (vendor_price, item_id),
    CONSTRAINT fk_purchase_price_item_id FOREIGN KEY (item_id) REFERENCES item (id)
);
CREATE INDEX ix_purchase_price_item_id ON purchase_price (item_id);

-- cart_item: 장바구니 — AS IS `B_CART`
CREATE TABLE cart_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    app_user_id bigint,
    cart_no integer,
    seq integer,
    item_id bigint,
    qty numeric(15,4),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(50) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(50) NOT NULL,
    CONSTRAINT pk_cart_item PRIMARY KEY (id),
    CONSTRAINT uq_cart_item_app_user_id_cart_no_seq UNIQUE (app_user_id, cart_no, seq),
    CONSTRAINT fk_cart_item_app_user_id FOREIGN KEY (app_user_id) REFERENCES app_user (id),
    CONSTRAINT fk_cart_item_item_id FOREIGN KEY (item_id) REFERENCES item (id)
);
CREATE INDEX ix_cart_item_item_id ON cart_item (item_id);
